/**
 * Generates migration 037 — legal URLs, terms acceptance and promotional consent.
 *
 * A GENERATOR, not a hand-written .sql file, for the same reason as 028 and
 * 029: the trigger body needs PostgreSQL dollar-quoting, and that token is
 * corrupted by PowerShell (which expands it to the shell PID) and by
 * JavaScript replace() (where it is an escape sequence). Building it from char
 * codes sidesteps both.
 *
 * Run: node scripts/gen-migration-037.mjs
 */
import { writeFileSync, readFileSync } from "node:fs";

const DQ = String.fromCharCode(36) + String.fromCharCode(36);

const sql = `-- ============================================================
-- LEGAL URLS, TERMS ACCEPTANCE AND PROMOTIONAL CONSENT
--
-- The signup form gains two checkboxes supplied by the client:
--
--   1. REQUIRED  - agreement to the Privacy Policy and Terms & Conditions.
--   2. OPTIONAL  - consent to promotional messages by SMS, email and phone,
--                  including an automatic telephone dialing system.
--
-- WHY THE SECOND IS NOT marketing_consent. That column (migration 028) was
-- written against an email-only checkbox. This consent is materially broader:
-- it covers SMS, voice calls and autodialing. Writing it into the same column
-- would retroactively reinterpret every existing row as permission to call
-- and text that person, which none of them gave. Consent must record what was
-- actually agreed to, so it gets its own column and the old one is left alone.
--
-- WHY TERMS ACCEPTANCE IS A TIMESTAMP, NOT A BOOLEAN. The question is never
-- "does this user agree" - it is "when did this person agree", which is what
-- has to be produced if it is ever disputed. A boolean cannot answer that.
--
-- THE URLS LIVE IN app_settings, NOT IN THE CODE. Same reasoning as migration
-- 033's booking URLs: a policy moves, gets a new host, or is replaced by a
-- third-party service, and none of that should need a redeploy. The signup
-- form reads them through a public endpoint and renders plain text instead of
-- a dead link when they are unset.
--
-- GENERATED by scripts/gen-migration-037.mjs. Edit that, not this.
-- SAFE TO RE-RUN: every statement is guarded.
-- ============================================================

-- ------------------------------------------------------------
-- 1. The columns.
-- ------------------------------------------------------------
ALTER TABLE app_settings
  ADD COLUMN IF NOT EXISTS privacy_policy_url TEXT,
  ADD COLUMN IF NOT EXISTS terms_url TEXT;

COMMENT ON COLUMN app_settings.privacy_policy_url IS
  'Public Privacy Policy URL, linked from the signup checkbox. NULL renders the label as plain text rather than a dead link.';

COMMENT ON COLUMN app_settings.terms_url IS
  'Public Terms and Conditions URL, linked from the signup checkbox. NULL renders the label as plain text rather than a dead link.';

ALTER TABLE profiles
  ADD COLUMN IF NOT EXISTS terms_accepted_at TIMESTAMPTZ,
  ADD COLUMN IF NOT EXISTS promotional_consent BOOLEAN,
  ADD COLUMN IF NOT EXISTS promotional_consent_at TIMESTAMPTZ;

COMMENT ON COLUMN profiles.terms_accepted_at IS
  'When this person accepted the Privacy Policy and Terms. NULL means never asked - admin-created and invited users never see the checkbox.';

COMMENT ON COLUMN profiles.promotional_consent IS
  'Consent to promotional SMS, email and phone including automated dialing. TRUE agreed, FALSE declined, NULL never asked. Separate from marketing_consent, which was email-only.';

COMMENT ON COLUMN profiles.promotional_consent_at IS
  'When promotional_consent was given or refused. Paired with the flag so the record says what was agreed and when.';

-- ------------------------------------------------------------
-- 2. Rebuild the signup trigger so the number actually lands.
--
-- RESTATED IN FULL, copied from 029 with v_phone added. CREATE OR REPLACE
-- cannot patch a function body, so a partial redefinition would silently drop
-- the trial resolution from 029, the trial setup from 023 or the consent
-- handling from 028. The only changes from 029 are the v_phone declaration,
-- its assignment, and the two extra lines in the profiles INSERT.
--
-- WITHOUT THIS the phone number is written into auth.users.raw_user_meta_data
-- by signUp() and then ignored forever, because nothing else reads that key.
-- The column alone is not enough.
-- ------------------------------------------------------------
CREATE OR REPLACE FUNCTION public.handle_new_user()
RETURNS TRIGGER
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS ${DQ}
DECLARE
  new_company_id UUID;
  v_company_name TEXT;
  v_first TEXT;
  v_last TEXT;
  v_trial_enabled BOOLEAN;
  v_trial_days INT;
  v_trial_plan UUID;
  v_tier TEXT;
  v_consent BOOLEAN;
  v_phone TEXT;
  v_terms_at TIMESTAMPTZ;
  v_promo BOOLEAN;
BEGIN
  v_first := COALESCE(NEW.raw_user_meta_data->>'first_name', '');
  v_last  := COALESCE(NEW.raw_user_meta_data->>'last_name', '');
  v_company_name := COALESCE(
    NULLIF(NEW.raw_user_meta_data->>'company_name', ''),
    v_first || E'\\x27' || 's Company'
  );

  -- Marketing consent (migration 028). Absent metadata stays NULL: a user
  -- created by an admin or team invite never saw the checkbox, and recording a
  -- refusal they never gave would be inventing an answer.
  v_consent := CASE
    WHEN NEW.raw_user_meta_data->>'marketing_consent' = 'true'  THEN TRUE
    WHEN NEW.raw_user_meta_data->>'marketing_consent' = 'false' THEN FALSE
    ELSE NULL
  END;

  /*
   * Phone (migration 035). NULLIF so an empty string becomes NULL rather than
   * being stored as '', keeping "asked and left blank" distinct from "never
   * asked" — the same distinction consent above is careful about. Already
   * normalised client-side; no reformatting here, because the trigger must not
   * hold a second opinion about what a valid number looks like.
   */
  v_phone := NULLIF(TRIM(COALESCE(NEW.raw_user_meta_data->>'phone', '')), '');

  /*
   * Terms and privacy acceptance (migration 037).
   *
   * A TIMESTAMP, NOT A BOOLEAN. The question is never "do they agree" — it is
   * "when did this person agree", because that is what has to be produced if
   * it is ever disputed. A true/false column cannot answer it.
   *
   * NULL for an admin-created or invited user, who never saw the checkbox.
   */
  v_terms_at := CASE
    WHEN NEW.raw_user_meta_data->>'terms_accepted' = 'true' THEN NOW()
    ELSE NULL
  END;

  /*
   * Promotional consent (migration 037) — SMS, phone and email, including
   * automated dialing.
   *
   * DELIBERATELY NOT marketing_consent. That column was written against an
   * email-only checkbox, and this consent is materially broader. Reusing it
   * would retroactively reinterpret every existing row as consent to be
   * called and texted by an autodialer, which nobody gave.
   *
   * Same tri-state as consent above: TRUE agreed, FALSE declined, NULL never
   * asked.
   */
  v_promo := CASE
    WHEN NEW.raw_user_meta_data->>'promotional_consent' = 'true'  THEN TRUE
    WHEN NEW.raw_user_meta_data->>'promotional_consent' = 'false' THEN FALSE
    ELSE NULL
  END;

  INSERT INTO companies (name, description, fiscal_year, planning_year, currency)
  VALUES (
    v_company_name, '',
    EXTRACT(YEAR FROM NOW())::INT,
    EXTRACT(YEAR FROM NOW())::INT,
    'USD'
  )
  RETURNING id INTO new_company_id;

  INSERT INTO profiles (
    id, company_id, email, first_name, last_name, role, is_admin,
    marketing_consent, marketing_consent_at, phone,
    terms_accepted_at, promotional_consent, promotional_consent_at
  )
  VALUES (
    NEW.id, new_company_id, NEW.email, v_first, v_last, 'owner', FALSE,
    v_consent,
    CASE WHEN v_consent IS NULL THEN NULL ELSE NOW() END,
    v_phone,
    v_terms_at,
    v_promo,
    CASE WHEN v_promo IS NULL THEN NULL ELSE NOW() END
  );

  INSERT INTO annual_plans (
    company_id, year, baseline_revenue, stretch_revenue, operating_budget, status
  )
  VALUES (new_company_id, EXTRACT(YEAR FROM NOW())::INT, 0, 0, 0, 'draft');

  SELECT
    COALESCE(trial_enabled, TRUE),
    COALESCE(NULLIF(trial_days, 0), 14)
  INTO v_trial_enabled, v_trial_days
  FROM app_settings WHERE id = 'global';

  v_trial_enabled := COALESCE(v_trial_enabled, TRUE);
  v_trial_days    := COALESCE(v_trial_days, 14);

  -- Active-plan resolution, shared with any admin tooling.
  v_trial_plan := public.resolve_trial_plan();

  -- Tier from the resolved plan, lower-cased, rather than a hardcoded
  -- 'starter' that may name no existing plan.
  SELECT LOWER(REPLACE(p.name, ' ', '_')) INTO v_tier
  FROM subscription_plans p WHERE p.id = v_trial_plan;

  v_tier := COALESCE(v_tier, 'none');

  /*
   * NO PLAN AT ALL -> no trial, whatever the setting says.
   *
   * A trial with a NULL plan_id finds no plan_limits rows, and a missing limit
   * is treated as unlimited — so an unconfigured deployment would hand out
   * unlimited access. Refusing is the safe failure: the user registers, sees
   * the purchase screen, and an admin can fix the configuration.
   */
  IF v_trial_plan IS NULL THEN
    v_trial_enabled := FALSE;
  END IF;

  INSERT INTO subscriptions (
    company_id, tier, status, billing_cycle, plan_id,
    is_trial_active, trial_ends_at, start_date
  )
  VALUES (
    new_company_id,
    v_tier,
    CASE WHEN v_trial_enabled THEN 'trial' ELSE 'cancelled' END,
    'monthly',
    -- Only a TRIAL gets a plan up front. With trials off the user has bought
    -- nothing yet, so leaving plan_id set would grant that plan's limits for
    -- free until they paid.
    CASE WHEN v_trial_enabled THEN v_trial_plan ELSE NULL END,
    v_trial_enabled,
    CASE WHEN v_trial_enabled THEN NOW() + (v_trial_days || ' days')::INTERVAL ELSE NULL END,
    NOW()
  );

  RETURN NEW;
END;
${DQ};

DROP TRIGGER IF EXISTS on_auth_user_created ON auth.users;
CREATE TRIGGER on_auth_user_created
  AFTER INSERT ON auth.users
  FOR EACH ROW
  EXECUTE FUNCTION public.handle_new_user();
`;

const path = "supabase/migrations/037_legal_consent.sql";
writeFileSync(path, sql, "utf8");

/**
 * Verified by reading the file BACK OFF DISK, not by inspecting the string we
 * just built. The whole point of the generator is that `$$` survives the trip,
 * and only a re-read proves it did.
 */
const written = readFileSync(path, "utf8");

const pairs = (written.match(/\$\$/g) || []).length;
const lone = (written.replace(/\$\$/g, "").match(/\$/g) || []).length;
const hasLegalUrls =
  written.includes("ADD COLUMN IF NOT EXISTS privacy_policy_url TEXT") &&
  written.includes("ADD COLUMN IF NOT EXISTS terms_url TEXT");
const hasConsentColumns =
  written.includes("ADD COLUMN IF NOT EXISTS terms_accepted_at TIMESTAMPTZ") &&
  written.includes("ADD COLUMN IF NOT EXISTS promotional_consent BOOLEAN");
const readsTerms = written.includes("raw_user_meta_data->>'terms_accepted'");
const readsPromo = written.includes("raw_user_meta_data->>'promotional_consent'");
const insertsThem = /terms_accepted_at, promotional_consent, promotional_consent_at/.test(written);
/**
 * The trigger is RESTATED IN FULL from 035, so everything that migration and
 * its predecessors added has to survive. A partial redefinition would silently
 * drop the phone capture from 035, the trial resolution from 029 or the
 * consent handling from 028 — which is exactly the failure each of those
 * migrations warned about in turn.
 */
const keepsPhone = written.includes("raw_user_meta_data->>'phone'");
const keepsConsent = written.includes("raw_user_meta_data->>'marketing_consent'");
const keepsTrial = written.includes("public.resolve_trial_plan()");

console.log(`\nWrote ${path}`);
console.log(`  dollar-quote pairs    : ${pairs} (expect 2)`);
console.log(`  stray single $        : ${lone} (expect 0)`);
console.log(`  adds legal URLs       : ${hasLegalUrls}`);
console.log(`  adds consent columns  : ${hasConsentColumns}`);
console.log(`  trigger reads terms   : ${readsTerms}`);
console.log(`  trigger reads promo   : ${readsPromo}`);
console.log(`  trigger inserts both  : ${insertsThem}`);
console.log(`  still captures phone  : ${keepsPhone}   (from 035)`);
console.log(`  still captures consent: ${keepsConsent}   (from 028)`);
console.log(`  still resolves trial  : ${keepsTrial}   (from 029)`);

const ok =
  pairs === 2 && lone === 0 && hasLegalUrls && hasConsentColumns &&
  readsTerms && readsPromo && insertsThem &&
  keepsPhone && keepsConsent && keepsTrial;

console.log(ok ? "\nOK — safe to run in the SQL editor.\n" : "\nBROKEN — do not run.\n");

process.exit(ok ? 0 : 1);
