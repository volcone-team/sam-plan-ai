/**
 * Is migration 050 (the plan comparison table) applied, and what did it seed?
 *
 * READ-ONLY. SELECTs only on pricing_rows, pricing_row_plans,
 * subscription_plans and app_settings. Writes nothing, applies nothing.
 *
 * Usage: node scripts/verify-050.mjs
 */
import { createClient } from "@supabase/supabase-js";
import { readFileSync } from "node:fs";
for (const line of readFileSync(".env.local", "utf8").split("\n")) {
  const m = line.match(/^\s*([A-Z0-9_]+)\s*=\s*(.*)\s*$/);
  if (m) process.env[m[1]] ??= m[2].replace(/^["']|["']$/g, "");
}
const db = createClient(
  process.env.NEXT_PUBLIC_SUPABASE_URL,
  process.env.SUPABASE_SERVICE_ROLE_KEY
);
console.log("\nPlan comparison table (migration 050)\n");
const NOT_APPLIED =
  "\nmigration not applied — run supabase/migrations/050_pricing_table.sql\n" +
  "in the Supabase SQL editor (generated by scripts/gen-migration-050.mjs).\n" +
  "Until then /get-started and /choose-plan show the plan cards they show today.\n";

const checks = [
  ["pricing_rows", "id, section, label, sublabel, value_cents, display_order, is_active, created_at, updated_at", null],
  ["pricing_row_plans", "row_id, plan_id, included, value_cents", null],
  ["subscription_plans", "id, name, compare_at_monthly_cents, price_label", null],
  ["app_settings", "id, pricing_annual_note, pricing_annual_note_value_cents", "global"],
];
const data = {};
let missing = 0;
for (const [table, columns, id] of checks) {
  let q = db.from(table).select(columns);
  if (id) q = q.eq("id", id);
  const { data: rows, error } = await q;
  if (error) {
    missing++;
    console.log(`  MISSING  ${table} (${columns})`);
    console.log(`           ${error.message}`);
  } else {
    data[table] = rows ?? [];
    console.log(`  ok       ${table}  (${(rows ?? []).length} row(s))`);
  }
}
if (missing > 0) {
  console.log(NOT_APPLIED);
  process.exit(1);
}

const money = (c) => (c == null ? "—" : `${String.fromCharCode(36)}${(c / 100).toLocaleString("en-US")}`);
const plans = data.subscription_plans;
const planName = new Map(plans.map((p) => [p.id, p.name]));
console.log("\nPlans");
for (const p of plans) {
  console.log(`  ${p.name.padEnd(12)} compare-at ${money(p.compare_at_monthly_cents)}/mo   label ${p.price_label ?? "—"}`);
}
const note = data.app_settings[0];
console.log(`\nAnnual note: ${note?.pricing_annual_note ?? "—"}  (${money(note?.pricing_annual_note_value_cents)})`);

const rows = [...data.pricing_rows].sort(
  (a, b) => a.section.localeCompare(b.section) || a.display_order - b.display_order
);
const cells = data.pricing_row_plans;
for (const section of ["included", "bonus"]) {
  console.log(`\nSection: ${section}`);
  const totals = new Map();
  for (const r of rows.filter((x) => x.section === section)) {
    const parts = cells
      .filter((c) => c.row_id === r.id)
      .map((c) => {
        const v = c.included ? (c.value_cents ?? r.value_cents ?? 0) : 0;
        if (r.is_active) totals.set(c.plan_id, (totals.get(c.plan_id) ?? 0) + v);
        return `${planName.get(c.plan_id) ?? c.plan_id}=${c.included ? (c.value_cents != null ? money(c.value_cents) : "yes") : "no"}`;
      });
    console.log(`  ${r.is_active ? " " : "x"} ${r.display_order.toString().padStart(3)} ${r.label}  [${money(r.value_cents)}]  ${parts.join(" ")}`);
  }
  for (const [planId, total] of totals) {
    console.log(`    total ${planName.get(planId) ?? planId}: ${money(total)}`);
  }
}
console.log("\nApplied.\n");
