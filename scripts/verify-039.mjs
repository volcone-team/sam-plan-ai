/**
 * Is migration 039 (FAQ) applied, seeded and locked down?
 *
 * Checks:
 *   1. Both tables exist (service role).
 *   2. Category and item counts, items by status.
 *   3. RLS: an ANON-key select on each table returns 0 rows or an error. A row
 *      coming back here means a policy exposes FAQ rows (drafts included).
 *
 * Read-only. Usage: node scripts/verify-039.mjs
 */

import { createClient } from "@supabase/supabase-js";
import { readFileSync } from "node:fs";

for (const line of readFileSync(".env.local", "utf8").split("\n")) {
  const m = line.match(/^\s*([A-Z0-9_]+)\s*=\s*(.*)\s*$/);
  if (m) process.env[m[1]] ??= m[2].replace(/^["']|["']$/g, "");
}

const url = process.env.NEXT_PUBLIC_SUPABASE_URL;
const db = createClient(url, process.env.SUPABASE_SERVICE_ROLE_KEY);
const anon = createClient(url, process.env.NEXT_PUBLIC_SUPABASE_ANON_KEY, {
  auth: { persistSession: false },
});

const TABLES = ["faq_categories", "faq_items"];

console.log("\nFAQ (migration 039)\n");

let missing = false;
for (const table of TABLES) {
  // NOT a head:true count — a HEAD request against a missing table comes back
  // with no error body, which reads as "exists". A real select reports it.
  const { error } = await db.from(table).select("*").limit(1);
  if (error) {
    console.log(`  MISSING  ${table}  — ${error.message}`);
    missing = true;
  } else {
    console.log(`  ok       ${table}`);
  }
}

if (missing) {
  console.log(
    "\nmigration not applied — run supabase/migrations/039_faq.sql\n" +
    "in the Supabase SQL editor (generated by scripts/gen-migration-039.mjs).\n"
  );
  process.exit(1);
}

// ---------------------------------------------------------------
// Counts
// ---------------------------------------------------------------
const [{ data: categories }, { data: items }] = await Promise.all([
  db.from("faq_categories").select("id, slug, is_published").order("display_order"),
  db.from("faq_items").select("id, category_id, status"),
]);

const rows = items ?? [];
const byStatus = rows.reduce((acc, r) => ({ ...acc, [r.status]: (acc[r.status] ?? 0) + 1 }), {});

console.log(`\n  categories : ${(categories ?? []).length} (seed: 4)`);
for (const c of categories ?? []) {
  const n = rows.filter((r) => r.category_id === c.id).length;
  console.log(`    ${c.is_published ? "      " : "hidden"} ${c.slug.padEnd(20)} ${n} item(s)`);
}
console.log(`  items      : ${rows.length} (seed: 14)`);
console.log(`    by status: ${JSON.stringify(byStatus)}`);

// ---------------------------------------------------------------
// RLS — the anon key must see nothing.
// ---------------------------------------------------------------
console.log("\n  RLS (anon key):");
let leaked = false;
for (const table of TABLES) {
  const { data, error } = await anon.from(table).select("*").limit(5);
  if (error) {
    console.log(`    ok       ${table}  — refused (${error.message})`);
  } else if ((data ?? []).length === 0) {
    console.log(`    ok       ${table}  — 0 rows`);
  } else {
    console.log(`    LEAK     ${table}  — anon read ${data.length} row(s)`);
    leaked = true;
  }
}

if (leaked) {
  console.log("\nFAILED — a policy exposes FAQ rows to anon. Remove it.\n");
  process.exit(1);
}

console.log("\nApplied.\n");
