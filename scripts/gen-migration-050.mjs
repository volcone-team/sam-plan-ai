/**
 * Generates migration 050 — the plan comparison table shown on /get-started
 * and /choose-plan (pricing_rows, pricing_row_plans, two subscription_plans
 * columns and two app_settings columns), with the founding-member seed.
 *
 * A GENERATOR, to match 028/029/035/037-049. The output contains no dollar
 * sign (checked on read-back): no dollar-quoting, no DO blocks, no functions.
 * Policies use DROP POLICY IF EXISTS + CREATE POLICY, as 045 does.
 *
 * SAFE TO RE-RUN. Every DDL statement is guarded. The seed:
 *   - inserts rows ONLY when pricing_rows is empty, and inserts cells only for
 *     the rows that same statement just created (data-modifying CTE), so a
 *     re-run never re-creates a row or cell an admin deleted;
 *   - finds plans BY NAME ('Starter', 'Pro'); a missing plan gets no cells;
 *   - fills plan / app_settings columns only where they are still NULL, so a
 *     re-run never overwrites an admin's edit.
 *
 * Run: node scripts/gen-migration-050.mjs
 */
import { writeFileSync, readFileSync } from "node:fs";
/** Built, never typed, so no shell or String.replace can mangle it. */
const DOLLAR = String.fromCharCode(36);

/**
 * The seed, in cents. starter/pro: [included, plan-specific value_cents].
 * Kept in step with SEED in src/lib/billing/pricing-table.test.ts, which
 * asserts the column totals.
 */
const SEED = [
  ["included", "Full SAM Plan App", "Targets · Initiative Library · FIT then SCORE · Plan · Build Checklist · Task lists · Dashboard", null, 10, [true, 30000], [true, 50000]],
  ["included", "In-app training library", null, 49700, 20, [true, null], [true, null]],
  ["included", "Live Support by email and chat", null, 9700, 30, [true, null], [true, null]],
  ["included", "2 extra team seats", null, 19800, 40, [false, null], [true, null]],
  ["bonus", "1:1 Onboarding Call", null, 50000, 10, [true, null], [true, null]],
  ["bonus", "ROS meeting agenda", null, 99700, 20, [true, null], [true, null]],
  ["bonus", "Weekly live ROS meeting with Pete, Rachel & the team (12 months)", null, 1200000, 30, [false, null], [true, null]],
  ["bonus", "Monthly best practices training with a subject matter expert (12 months)", null, 596400, 40, [false, null], [true, null]],
];

const lit = (v) =>
  v === null ? "NULL" : typeof v === "string" ? `'${v.replace(/'/g, "''")}'` : String(v);
const seedValues = SEED.map(
  ([section, label, sublabel, value, order, [sInc, sVal], [pInc, pVal]]) =>
    `    (${[section, label, sublabel, value, order, sInc, sVal, pInc, pVal].map(lit).join(", ")})`
).join(",\n");

const sql = `-- ============================================================
-- PLAN COMPARISON TABLE
--
-- The "what you get" table on /get-started and /choose-plan: a list of rows in
-- two sections (included / bonus), each with an optional "497 dollar Value" figure,
-- and one cell per plan saying whether that plan includes the row, or a
-- plan-specific figure shown in its column instead of a tick (300 or 500 dollars).
-- Plus a crossed-out monthly price and a price label per plan, and one
-- annual-billing note with its own value figure.
--
-- Edited at /admin/subscriptions > Manage Plans > Comparison table.
-- Read server-side by src/lib/billing/load-pricing-table.ts, which treats a
-- missing table or column as "not applied" and lets the pages show the plan
-- cards they show today. So the release does not depend on this being run
-- first.
--
-- All money is INTEGER CENTS (bigint), unlike subscription_plans.monthly_price
-- (NUMERIC dollars, 004), because these are display figures summed into
-- column totals and cents keep that sum exact.
--
-- GENERATED by scripts/gen-migration-050.mjs. Edit that, not this.
-- SAFE TO RE-RUN: every statement is guarded and the seed never overwrites or
-- re-creates anything an admin has changed or deleted.
-- ============================================================
-- ------------------------------------------------------------
-- 1. Rows.
-- ------------------------------------------------------------
CREATE TABLE IF NOT EXISTS pricing_rows (
  id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  section TEXT NOT NULL,
  label TEXT NOT NULL,
  sublabel TEXT,
  -- The "Value" figure next to the label (497 dollars = 49700). NULL = show none.
  value_cents BIGINT,
  display_order INT NOT NULL DEFAULT 0,
  is_active BOOLEAN NOT NULL DEFAULT TRUE,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
ALTER TABLE pricing_rows DROP CONSTRAINT IF EXISTS pricing_rows_section_check;
ALTER TABLE pricing_rows ADD CONSTRAINT pricing_rows_section_check
  CHECK (section IN ('included', 'bonus'));
ALTER TABLE pricing_rows DROP CONSTRAINT IF EXISTS pricing_rows_label_check;
ALTER TABLE pricing_rows ADD CONSTRAINT pricing_rows_label_check
  CHECK (length(btrim(label)) > 0);
ALTER TABLE pricing_rows DROP CONSTRAINT IF EXISTS pricing_rows_value_cents_check;
ALTER TABLE pricing_rows ADD CONSTRAINT pricing_rows_value_cents_check
  CHECK (value_cents IS NULL OR value_cents >= 0);
COMMENT ON TABLE pricing_rows IS
  'Rows of the plan comparison table on /get-started and /choose-plan. section included|bonus; value_cents is the row-level "Value" figure (NULL = none). Inactive rows are hidden.';
CREATE INDEX IF NOT EXISTS idx_pricing_rows_section_order
  ON pricing_rows(section, display_order);
-- ------------------------------------------------------------
-- 2. One cell per (row, plan).
--
-- included = FALSE (or no cell at all): the plan column shows "not included".
-- included = TRUE, value_cents NULL: a tick; the column total counts the
-- row's own value_cents.
-- included = TRUE, value_cents set: that figure is shown in the plan column
-- instead of a tick, and counted in the total instead of the row's figure.
-- ------------------------------------------------------------
CREATE TABLE IF NOT EXISTS pricing_row_plans (
  row_id UUID NOT NULL REFERENCES pricing_rows(id) ON DELETE CASCADE,
  plan_id UUID NOT NULL REFERENCES subscription_plans(id) ON DELETE CASCADE,
  included BOOLEAN NOT NULL DEFAULT FALSE,
  value_cents BIGINT,
  PRIMARY KEY (row_id, plan_id)
);
ALTER TABLE pricing_row_plans DROP CONSTRAINT IF EXISTS pricing_row_plans_value_cents_check;
ALTER TABLE pricing_row_plans ADD CONSTRAINT pricing_row_plans_value_cents_check
  CHECK (value_cents IS NULL OR value_cents >= 0);
COMMENT ON TABLE pricing_row_plans IS
  'Per-plan cell of the comparison table. Missing or included=false: not included. included with value_cents: a plan-specific figure shown instead of a tick.';
-- The primary key covers lookups by row; this covers ON DELETE CASCADE from
-- subscription_plans and "every cell of one plan".
CREATE INDEX IF NOT EXISTS idx_pricing_row_plans_plan
  ON pricing_row_plans(plan_id);
-- ------------------------------------------------------------
-- 3. Per-plan display extras.
-- ------------------------------------------------------------
ALTER TABLE subscription_plans
  ADD COLUMN IF NOT EXISTS compare_at_monthly_cents BIGINT,
  ADD COLUMN IF NOT EXISTS price_label TEXT;
ALTER TABLE subscription_plans
  DROP CONSTRAINT IF EXISTS subscription_plans_compare_at_monthly_cents_check;
ALTER TABLE subscription_plans
  ADD CONSTRAINT subscription_plans_compare_at_monthly_cents_check
  CHECK (compare_at_monthly_cents IS NULL OR compare_at_monthly_cents >= 0);
COMMENT ON COLUMN subscription_plans.compare_at_monthly_cents IS
  'Crossed-out monthly price on the comparison table, in cents. The annual figure is this x 12. Display only: never charged, never synced to Stripe. NULL = none.';
COMMENT ON COLUMN subscription_plans.price_label IS
  'Short label above the price on the comparison table, e.g. Founding Price. NULL = none.';
-- ------------------------------------------------------------
-- 4. The annual-billing note (app_settings singleton, 020).
-- ------------------------------------------------------------
ALTER TABLE app_settings
  ADD COLUMN IF NOT EXISTS pricing_annual_note TEXT,
  ADD COLUMN IF NOT EXISTS pricing_annual_note_value_cents BIGINT;
ALTER TABLE app_settings
  DROP CONSTRAINT IF EXISTS app_settings_pricing_annual_note_value_cents_check;
ALTER TABLE app_settings
  ADD CONSTRAINT app_settings_pricing_annual_note_value_cents_check
  CHECK (pricing_annual_note_value_cents IS NULL OR pricing_annual_note_value_cents >= 0);
COMMENT ON COLUMN app_settings.pricing_annual_note IS
  'Note shown with annual billing on the comparison table, e.g. 2 months free + onboarding call. NULL = none.';
COMMENT ON COLUMN app_settings.pricing_annual_note_value_cents IS
  'Value figure shown with pricing_annual_note, in cents. NULL = none.';
-- ------------------------------------------------------------
-- 5. updated_at maintenance, using update_updated_at() from migration 001
--    (the same function subscription_plans uses since 004).
-- ------------------------------------------------------------
DROP TRIGGER IF EXISTS set_updated_at ON pricing_rows;
CREATE TRIGGER set_updated_at BEFORE UPDATE ON pricing_rows
  FOR EACH ROW EXECUTE FUNCTION update_updated_at();
-- ------------------------------------------------------------
-- 6. RLS: ENABLED, public SELECT, writes service-role only.
--
-- /get-started is a public page, and nothing here is secret: it is the same
-- marketing table every visitor sees. The app reads it with the service role
-- regardless; the read policy only means a direct anon read is not an error.
-- No INSERT / UPDATE / DELETE policy, so only the service role (the
-- super-admin route /api/admin/pricing-table) can write.
-- ------------------------------------------------------------
ALTER TABLE pricing_rows ENABLE ROW LEVEL SECURITY;
ALTER TABLE pricing_row_plans ENABLE ROW LEVEL SECURITY;
DROP POLICY IF EXISTS "Anyone can read pricing rows" ON pricing_rows;
CREATE POLICY "Anyone can read pricing rows"
  ON pricing_rows
  FOR SELECT
  TO anon, authenticated
  USING (true);
DROP POLICY IF EXISTS "Anyone can read pricing row plans" ON pricing_row_plans;
CREATE POLICY "Anyone can read pricing row plans"
  ON pricing_row_plans
  FOR SELECT
  TO anon, authenticated
  USING (true);
-- ------------------------------------------------------------
-- 7. SEED — the founding-member table.
--
-- One statement: the rows are inserted only when pricing_rows is empty, and
-- the cells only for the rows this statement inserted, for whichever of the
-- plans named exactly Starter / Pro exist. Re-running inserts nothing.
-- ------------------------------------------------------------
WITH seed (section, label, sublabel, value_cents, display_order,
           starter_included, starter_value_cents, pro_included, pro_value_cents) AS (
  VALUES
${seedValues}
),
inserted AS (
  INSERT INTO pricing_rows (section, label, sublabel, value_cents, display_order)
  SELECT s.section, s.label, s.sublabel::TEXT, s.value_cents::BIGINT, s.display_order
  FROM seed s
  WHERE NOT EXISTS (SELECT 1 FROM pricing_rows)
  RETURNING id, label
)
INSERT INTO pricing_row_plans (row_id, plan_id, included, value_cents)
SELECT i.id,
       p.id,
       CASE WHEN p.name = 'Starter' THEN s.starter_included ELSE s.pro_included END,
       (CASE WHEN p.name = 'Starter' THEN s.starter_value_cents ELSE s.pro_value_cents END)::BIGINT
FROM inserted i
JOIN seed s ON s.label = i.label
JOIN subscription_plans p ON p.name IN ('Starter', 'Pro')
ON CONFLICT (row_id, plan_id) DO NOTHING;
-- Crossed-out monthly prices and the price label, only where not yet set.
UPDATE subscription_plans SET compare_at_monthly_cents = 9900
  WHERE name = 'Starter' AND compare_at_monthly_cents IS NULL;
UPDATE subscription_plans SET compare_at_monthly_cents = 19900
  WHERE name = 'Pro' AND compare_at_monthly_cents IS NULL;
UPDATE subscription_plans SET price_label = 'Founding Price'
  WHERE name IN ('Starter', 'Pro') AND price_label IS NULL;
-- The annual note, only where not yet set.
UPDATE app_settings SET pricing_annual_note = '2 months free + onboarding call with Pete'
  WHERE id = 'global' AND pricing_annual_note IS NULL;
UPDATE app_settings SET pricing_annual_note_value_cents = 250000
  WHERE id = 'global' AND pricing_annual_note_value_cents IS NULL;
`;

const path = "supabase/migrations/050_pricing_table.sql";
writeFileSync(path, sql, "utf8");
const written = readFileSync(path, "utf8");
const dollars = written.split(DOLLAR).length - 1;
const code = written
  .split("\n")
  .filter((l) => !l.trimStart().startsWith("--"))
  .join("\n");
const updates = code.match(/^UPDATE [\s\S]*?;/gm) ?? [];
const checks = {
  "file matches what was generated": written === sql,
  "no DO blocks / functions":
    !/^\s*DO\b/m.test(written) && !/CREATE (OR REPLACE )?FUNCTION/i.test(written),
  "no destructive statements":
    !/DROP\s+(TABLE|COLUMN|INDEX)|TRUNCATE|DELETE FROM/i.test(code),
  "every UPDATE only fills a NULL": updates.length === 5 && updates.every((u) => /IS NULL;\s*$/.test(u)),
  "row seed guarded by an empty-table check": /WHERE NOT EXISTS \(SELECT 1 FROM pricing_rows\)/.test(code),
  "cell seed is ON CONFLICT DO NOTHING": /ON CONFLICT \(row_id, plan_id\) DO NOTHING;/.test(code),
  [`seed has ${SEED.length} rows`]: (code.match(/^\s+\('(included|bonus)'/gm) ?? []).length === SEED.length,
  "quote-balanced outside the dash comments": (code.match(/'/g) || []).length % 2 === 0,
};
console.log(`\nWrote ${path}`);
console.log(`  dollar signs          : ${dollars} (expect 0)`);
for (const [label, ok] of Object.entries(checks)) {
  console.log(`  ${ok ? "ok    " : "FAILED"} ${label}`);
}
const ok = dollars === 0 && Object.values(checks).every(Boolean);
console.log(ok ? "\nOK — safe to run in the SQL editor.\n" : "\nBROKEN — do not run.\n");
process.exit(ok ? 0 : 1);
