/**
 * Is migration 052 (ghl_events.event_type accepts 'registered') applied?
 *
 * READ-ONLY. Reads the CHECK definition through the optional
 * pg_get_constraintdef_by_name RPC. Inserts nothing: proving the CHECK by
 * writing a 'registered' row would put an outbox row on the database dev and
 * production share, and the drain could deliver it. Where the catalog cannot
 * be read from here the script says SKIP and prints the query to paste.
 *
 * Exits 1 when the CHECK is readable and does not list 'registered', or when
 * ghl_events itself cannot be read.
 *
 * Usage: node scripts/verify-052.mjs
 */
import { createClient } from "@supabase/supabase-js";
import { readFileSync } from "node:fs";

for (const line of readFileSync(".env.local", "utf8").split("\n")) {
  const m = line.match(/^\s*([A-Z0-9_]+)\s*=\s*(.*)\s*$/);
  if (m) process.env[m[1]] ??= m[2].replace(/^["']|["']$/g, "");
}

const db = createClient(process.env.NEXT_PUBLIC_SUPABASE_URL, process.env.SUPABASE_SERVICE_ROLE_KEY);
const NAME = "ghl_events_event_type_check";

console.log("\nGHL 'registered' event (migration 052)\n");

const { error: tableError } = await db.from("ghl_events").select("id, event_type").limit(1);
if (tableError) {
  console.log(`  MISSING  ghl_events — ${tableError.message} (apply 044 first)`);
  process.exit(1);
}
console.log("  ok       ghl_events readable");

const { data, error } = await db.rpc("pg_get_constraintdef_by_name", { conname: NAME });
if (error || typeof data !== "string") {
  console.log(`  SKIP     ${NAME} (cannot read the catalog from here)`);
  console.log(
    "\n  Confirm by hand in the SQL editor:\n" +
      "    SELECT conname, pg_get_constraintdef(oid) FROM pg_constraint\n" +
      "     WHERE contype = 'c' AND conrelid = 'public.ghl_events'::regclass\n" +
      "       AND pg_get_constraintdef(oid) ILIKE '%event_type%';\n" +
      "  Exactly one row, and it must list 'registered'.\n"
  );
  process.exit(0);
}

if (data.includes("'registered'")) {
  console.log(`  ok       ${NAME} accepts 'registered'`);
  console.log("\nApplied.\n");
} else {
  console.log(`  STALE    ${NAME} does not list 'registered'`);
  console.log(`           ${data}`);
  console.log(
    "\nmigration not applied — run supabase/migrations/052_ghl_registered_event.sql\n" +
      "in the Supabase SQL editor (generated by scripts/gen-migration-052.mjs).\n" +
      "Until then registration events are refused (23514) and reported as not delivered.\n"
  );
  process.exit(1);
}
