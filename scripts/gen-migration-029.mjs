/**
 * Generates migration 029 — trial plan resolution.
 *
 * A GENERATOR, not a .sql file, for the same reason as 028: the function body
 * needs PostgreSQL dollar-quoting, and that token gets corrupted by PowerShell
 * (which expands it to the shell PID) and by JavaScript replace() (where it is
 * an escape sequence). Building it from char codes avoids both.
 *
 * Run: node scripts/gen-migration-029.mjs
 */
import { writeFileSync } from "node:fs";

const DQ = String.fromCharCode(36) + String.fromCharCode(36);

const sql = `-- ============================================================
-- TRIAL PLAN RESOLUTION
--
-- THREE BUGS in handle_new_user() as migration 023 left it, all of which
-- surface once a plan is retired or renamed.
--
-- 1. \`tier\` was hardcoded to 'starter'. Nothing branches on that column — it is
--    only ever read as a FALLBACK LABEL when plan_id cannot be resolved — but
--    that makes it worse, not better: a deployment with no plan called Starter
--    would show trial users a plan name that does not exist. It now carries the
--    resolved plan's own tier.
--
-- 2. The trial plan fell back to \`is_default\` WITHOUT checking is_active. With
--    the retire feature, the selected trial plan (or the default) can be
--    retired, so new signups would land on a plan nobody can buy or upgrade
--    from.
--
-- 3. If no default existed at all, v_trial_plan was left NULL. A NULL plan_id
--    means no plan_limits rows can be found, and checkEntitlement treats a
--    missing limit as unlimited — so a misconfiguration produced an UNLIMITED
--    trial rather than a refused one.
--
-- RESOLUTION ORDER, each step requiring an ACTIVE plan:
--   1. app_settings.trial_plan_id  (the admin's explicit choice)
--   2. the active default plan
--   3. the cheapest active plan    (there is always something to fall back to)
--
-- GENERATED by scripts/gen-migration-029.mjs. Edit that, not this.
-- SAFE TO RE-RUN: every statement is guarded.
-- ============================================================

-- ------------------------------------------------------------
-- 1. Widen the legacy tier constraint.
--
-- \`tier\` predates subscription_plans and allows only ('starter','pro',
-- 'mastery'), so writing a real plan's tier — 'founding_member', anything a
-- future plan is called — would violate the CHECK and fail the whole signup
-- trigger. The column is a display fallback, not a driver, so the constraint
-- buys nothing and costs new-plan support.
-- ------------------------------------------------------------
ALTER TABLE subscriptions DROP CONSTRAINT IF EXISTS subscriptions_tier_check;

COMMENT ON COLUMN subscriptions.tier IS
  'Legacy label, kept as a display fallback when plan_id cannot be resolved. plan_id is the source of truth; nothing branches on this.';

-- ------------------------------------------------------------
-- 2. One function for "which plan does a trial get".
--
-- Extracted so the trigger and any admin tooling cannot drift apart on the
-- answer. STABLE: it reads but never writes.
-- ------------------------------------------------------------
CREATE OR REPLACE FUNCTION public.resolve_trial_plan()
RETURNS UUID
LANGUAGE plpgsql
STABLE
SECURITY DEFINER
SET search_path = public
AS ${DQ}
DECLARE
  v_plan UUID;
BEGIN
  -- 1. The admin's explicit choice, but only while it is still sold.
  SELECT s.trial_plan_id INTO v_plan
  FROM app_settings s
  WHERE s.id = 'global'
    AND s.trial_plan_id IS NOT NULL
    AND EXISTS (
      SELECT 1 FROM subscription_plans p
      WHERE p.id = s.trial_plan_id AND p.is_active
    );

  IF v_plan IS NOT NULL THEN
    RETURN v_plan;
  END IF;

  -- 2. The active default.
  SELECT p.id INTO v_plan
  FROM subscription_plans p
  WHERE p.is_default AND p.is_active
  ORDER BY p.display_order
  LIMIT 1;

  IF v_plan IS NOT NULL THEN
    RETURN v_plan;
  END IF;

  -- 3. The cheapest active plan. A trial should grant the SMALLEST entitlement
  --    available, never accidentally the largest.
  SELECT p.id INTO v_plan
  FROM subscription_plans p
  WHERE p.is_active
  ORDER BY p.monthly_price, p.display_order
  LIMIT 1;

  RETURN v_plan;
END;
${DQ};

COMMENT ON FUNCTION public.resolve_trial_plan() IS
  'Trial plan: admin choice, else active default, else cheapest active. Every step requires is_active.';

-- ------------------------------------------------------------
-- 3. Rebuild the signup trigger.
--
-- Restated in full: CREATE OR REPLACE cannot patch a body, and a partial
-- redefinition would drop the consent handling from 028 or the trial setup
-- from 023.
-- ------------------------------------------------------------
CREATE OR REPLACE FUNCTION public.handle_new_user()
RETURNS TRIGGER
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS ${DQ}
DECLARE
  new_company_id UUID;
  v_company_name TEXT;
  v_first TEXT;
  v_last TEXT;
  v_trial_enabled BOOLEAN;
  v_trial_days INT;
  v_trial_plan UUID;
  v_tier TEXT;
  v_consent BOOLEAN;
BEGIN
  v_first := COALESCE(NEW.raw_user_meta_data->>'first_name', '');
  v_last  := COALESCE(NEW.raw_user_meta_data->>'last_name', '');
  v_company_name := COALESCE(
    NULLIF(NEW.raw_user_meta_data->>'company_name', ''),
    v_first || E'\\x27' || 's Company'
  );

  -- Marketing consent (migration 028). Absent metadata stays NULL: a user
  -- created by an admin or team invite never saw the checkbox, and recording a
  -- refusal they never gave would be inventing an answer.
  v_consent := CASE
    WHEN NEW.raw_user_meta_data->>'marketing_consent' = 'true'  THEN TRUE
    WHEN NEW.raw_user_meta_data->>'marketing_consent' = 'false' THEN FALSE
    ELSE NULL
  END;

  INSERT INTO companies (name, description, fiscal_year, planning_year, currency)
  VALUES (
    v_company_name, '',
    EXTRACT(YEAR FROM NOW())::INT,
    EXTRACT(YEAR FROM NOW())::INT,
    'USD'
  )
  RETURNING id INTO new_company_id;

  INSERT INTO profiles (
    id, company_id, email, first_name, last_name, role, is_admin,
    marketing_consent, marketing_consent_at
  )
  VALUES (
    NEW.id, new_company_id, NEW.email, v_first, v_last, 'owner', FALSE,
    v_consent,
    CASE WHEN v_consent IS NULL THEN NULL ELSE NOW() END
  );

  INSERT INTO annual_plans (
    company_id, year, baseline_revenue, stretch_revenue, operating_budget, status
  )
  VALUES (new_company_id, EXTRACT(YEAR FROM NOW())::INT, 0, 0, 0, 'draft');

  SELECT
    COALESCE(trial_enabled, TRUE),
    COALESCE(NULLIF(trial_days, 0), 14)
  INTO v_trial_enabled, v_trial_days
  FROM app_settings WHERE id = 'global';

  v_trial_enabled := COALESCE(v_trial_enabled, TRUE);
  v_trial_days    := COALESCE(v_trial_days, 14);

  -- Active-plan resolution, shared with any admin tooling.
  v_trial_plan := public.resolve_trial_plan();

  -- Tier from the resolved plan, lower-cased, rather than a hardcoded
  -- 'starter' that may name no existing plan.
  SELECT LOWER(REPLACE(p.name, ' ', '_')) INTO v_tier
  FROM subscription_plans p WHERE p.id = v_trial_plan;

  v_tier := COALESCE(v_tier, 'none');

  /*
   * NO PLAN AT ALL -> no trial, whatever the setting says.
   *
   * A trial with a NULL plan_id finds no plan_limits rows, and a missing limit
   * is treated as unlimited — so an unconfigured deployment would hand out
   * unlimited access. Refusing is the safe failure: the user registers, sees
   * the purchase screen, and an admin can fix the configuration.
   */
  IF v_trial_plan IS NULL THEN
    v_trial_enabled := FALSE;
  END IF;

  INSERT INTO subscriptions (
    company_id, tier, status, billing_cycle, plan_id,
    is_trial_active, trial_ends_at, start_date
  )
  VALUES (
    new_company_id,
    v_tier,
    CASE WHEN v_trial_enabled THEN 'trial' ELSE 'cancelled' END,
    'monthly',
    -- Only a TRIAL gets a plan up front. With trials off the user has bought
    -- nothing yet, so leaving plan_id set would grant that plan's limits for
    -- free until they paid.
    CASE WHEN v_trial_enabled THEN v_trial_plan ELSE NULL END,
    v_trial_enabled,
    CASE WHEN v_trial_enabled THEN NOW() + (v_trial_days || ' days')::INTERVAL ELSE NULL END,
    NOW()
  );

  RETURN NEW;
END;
${DQ};

DROP TRIGGER IF EXISTS on_auth_user_created ON auth.users;
CREATE TRIGGER on_auth_user_created
  AFTER INSERT ON auth.users
  FOR EACH ROW
  EXECUTE FUNCTION public.handle_new_user();
`;

const path = "supabase/migrations/029_trial_plan_resolution.sql";
writeFileSync(path, sql, "utf8");

const pairs = (sql.match(/\$\$/g) || []).length;
const lone = (sql.replace(/\$\$/g, "").match(/\$/g) || []).length;

console.log(`\nWrote ${path}`);
console.log(`  dollar-quote pairs : ${pairs} (expect 4)`);
console.log(`  stray single $     : ${lone} (expect 0)`);
console.log(
  pairs === 4 && lone === 0
    ? "\nOK — safe to run in the SQL editor.\n"
    : "\nBROKEN — do not run.\n"
);

process.exit(pairs === 4 && lone === 0 ? 0 : 1);
