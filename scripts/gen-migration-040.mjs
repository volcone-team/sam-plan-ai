/**
 * Generates migration 040 — library scores, industries, CTA options, training,
 * metrics and variant links on wb_initiative_library, plus the library link and
 * metric set on initiatives.
 *
 * A GENERATOR, not a hand-written .sql file, to match 028/029/035/037/038/039.
 * The output contains NO dollar sign at all — no dollar-quoting, no DO blocks,
 * no functions. The read-back check below asserts that, so a future edit
 * cannot sneak one in.
 *
 * Every statement is guarded (ADD COLUMN IF NOT EXISTS, DROP CONSTRAINT IF
 * EXISTS before ADD CONSTRAINT, CREATE INDEX IF NOT EXISTS), so it is safe to
 * re-run.
 *
 * Run: node scripts/gen-migration-040.mjs
 */
import { writeFileSync, readFileSync } from "node:fs";

/** Built, never typed, so no shell or String.replace can mangle it. */
const DOLLAR = String.fromCharCode(36);

const SCORES = [
  ["speed_score", "Speed (S)", "how soon it produces revenue"],
  ["cost_score", "Cost (C)", "how cheap it is to run"],
  ["odds_score", "Odds (O)", "how likely it is to work"],
  ["revenue_score", "Revenue (R)", "how much revenue it can produce"],
  ["ease_score", "Ease (E)", "how easy it is to run"],
];

const scoreColumns = SCORES.map(([c]) => `  ADD COLUMN IF NOT EXISTS ${c} SMALLINT`).join(",\n");

const scoreChecks = SCORES.map(([c]) => `ALTER TABLE wb_initiative_library
  DROP CONSTRAINT IF EXISTS wb_initiative_library_${c}_check;
ALTER TABLE wb_initiative_library
  ADD CONSTRAINT wb_initiative_library_${c}_check
  CHECK (${c} IS NULL OR ${c} BETWEEN 1 AND 5);`).join("\n");

const scoreComments = SCORES.map(([c, label, what]) => `COMMENT ON COLUMN wb_initiative_library.${c} IS
  'Workbook ${label} score, 1-5 where 5 is always best (${what}). NULL when the cell is blank or not a whole 1-5.';`).join("\n");

const sql = `-- ============================================================
-- WORKBOOK LIBRARY: SCORES, INDUSTRIES, CTA, TRAINING, METRICS
--
-- The client's Oct 2026 workbook has a 19-column Initiative Library: five
-- S/C/O/R/E scores, Ideal Industries, Call to Action Options, Training and a
-- free-text Metrics cell. It no longer has Difficulty or the text Speed; those
-- are DERIVED at ingest (src/lib/workbook/parse.ts deriveLegacyFields) and keep
-- living in the existing difficulty / speed_to_results columns.
--
-- wb_initiative_library is REPLACED WHOLESALE on every upload, so nothing here
-- is hand-edited data. Apply this, then upload the workbook again at
-- /admin/ai-workbook to fill the new columns.
--
-- Until this is applied, ingest stores the old column set and reports a
-- warning; the app reads the new fields as null / empty.
--
-- GENERATED by scripts/gen-migration-040.mjs. Edit that, not this.
-- SAFE TO RE-RUN: every statement is guarded.
-- ============================================================

-- ------------------------------------------------------------
-- 1. wb_initiative_library — new columns.
-- ------------------------------------------------------------
ALTER TABLE wb_initiative_library
  ADD COLUMN IF NOT EXISTS workbook_id TEXT,
  ADD COLUMN IF NOT EXISTS base_key TEXT,
${scoreColumns},
  ADD COLUMN IF NOT EXISTS score_total SMALLINT,
  ADD COLUMN IF NOT EXISTS ideal_industries TEXT[] NOT NULL DEFAULT '{}',
  ADD COLUMN IF NOT EXISTS cta_options TEXT[] NOT NULL DEFAULT '{}',
  ADD COLUMN IF NOT EXISTS training TEXT[] NOT NULL DEFAULT '{}',
  ADD COLUMN IF NOT EXISTS metrics_raw TEXT,
  ADD COLUMN IF NOT EXISTS metrics JSONB NOT NULL DEFAULT '[]';

-- Score range checks, added separately so re-running cannot fail on an
-- existing constraint and a check can be revised without touching the column.
${scoreChecks}

COMMENT ON COLUMN wb_initiative_library.workbook_id IS
  'The sheet''s own ID cell, e.g. IN11, verbatim. Not unique: the workbook reuses IDs across variants.';
COMMENT ON COLUMN wb_initiative_library.base_key IS
  'Set only on a variant listing (e.g. webinar-own): the initiative_key it is a variant of (webinar). Task templates and benchmarks join by name and so sit on the base key; readers fall back to it. NULL on a base listing. No FK: the table is replaced wholesale.';
${scoreComments}
COMMENT ON COLUMN wb_initiative_library.score_total IS
  'speed + cost + odds + revenue + ease, computed at ingest (the sheet''s own total is not trusted). NULL unless all five scores are present.';
COMMENT ON COLUMN wb_initiative_library.ideal_industries IS
  'Workbook Ideal Industries, one per element. Empty means no restriction (Broad fit). Read by passesIndustry in src/lib/recommend/eligibility.ts.';
COMMENT ON COLUMN wb_initiative_library.cta_options IS
  'Workbook Call to Action Options, one per element (e.g. Offer, Lead Collect).';
COMMENT ON COLUMN wb_initiative_library.training IS
  'Workbook Training entries, one per element.';
COMMENT ON COLUMN wb_initiative_library.metrics_raw IS
  'The workbook Metrics cell exactly as written, newlines included. Source for metrics.';
COMMENT ON COLUMN wb_initiative_library.metrics IS
  'Structured metrics parsed from metrics_raw. Empty array until the metrics parser fills it.';

-- ------------------------------------------------------------
-- 2. initiatives — link back to the library, and the metric set.
-- ------------------------------------------------------------
ALTER TABLE initiatives
  ADD COLUMN IF NOT EXISTS library_key TEXT,
  ADD COLUMN IF NOT EXISTS metric_set JSONB;

COMMENT ON COLUMN initiatives.library_key IS
  'wb_initiative_library.initiative_key this initiative was created from. NULL for hand-made initiatives and rows created before migration 040. Deliberately NO foreign key: the library is replaced wholesale on every workbook upload.';
COMMENT ON COLUMN initiatives.metric_set IS
  'The metrics this initiative tracks, copied from the library when it is created so a later workbook upload cannot change a running plan. NULL until filled.';

CREATE INDEX IF NOT EXISTS idx_initiatives_library_key
  ON initiatives(library_key);
`;

const path = "supabase/migrations/040_library_scores_metrics.sql";
writeFileSync(path, sql, "utf8");

/** Verified by reading the file BACK OFF DISK — only a re-read proves what will be pasted. */
const written = readFileSync(path, "utf8");
const dollars = written.split(DOLLAR).length - 1;
const has = (s) => written.includes(s);
const count = (re) => (written.match(re) || []).length;

const checks = {
  "workbook_id": has("ADD COLUMN IF NOT EXISTS workbook_id TEXT"),
  "base_key": has("ADD COLUMN IF NOT EXISTS base_key TEXT"),
  ...Object.fromEntries(SCORES.flatMap(([c]) => [
    [`${c} smallint`, has(`ADD COLUMN IF NOT EXISTS ${c} SMALLINT`)],
    [`${c} 1-5 check`, has(`CHECK (${c} IS NULL OR ${c} BETWEEN 1 AND 5)`)],
    [`${c} check guarded`, has(`DROP CONSTRAINT IF EXISTS wb_initiative_library_${c}_check`)],
  ])),
  "score_total": has("ADD COLUMN IF NOT EXISTS score_total SMALLINT"),
  "ideal_industries": has("ADD COLUMN IF NOT EXISTS ideal_industries TEXT[] NOT NULL DEFAULT '{}'"),
  "cta_options": has("ADD COLUMN IF NOT EXISTS cta_options TEXT[] NOT NULL DEFAULT '{}'"),
  "training": has("ADD COLUMN IF NOT EXISTS training TEXT[] NOT NULL DEFAULT '{}'"),
  "metrics_raw": has("ADD COLUMN IF NOT EXISTS metrics_raw TEXT"),
  "metrics jsonb": has("ADD COLUMN IF NOT EXISTS metrics JSONB NOT NULL DEFAULT '[]'"),
  "initiatives.library_key": has("ADD COLUMN IF NOT EXISTS library_key TEXT"),
  "initiatives.metric_set": has("ADD COLUMN IF NOT EXISTS metric_set JSONB"),
  "library_key index": has("CREATE INDEX IF NOT EXISTS idx_initiatives_library_key\n  ON initiatives(library_key);"),
  "no FK on library_key": !/REFERENCES\s+wb_initiative_library/i.test(written),
  "every ADD COLUMN guarded": count(/ADD COLUMN (?!IF NOT EXISTS)/g) === 0,
  "every ADD CONSTRAINT preceded by DROP": count(/ADD CONSTRAINT/g) === count(/DROP CONSTRAINT IF EXISTS/g),
  "15 column comments": count(/^COMMENT ON COLUMN/gm) === 15,
  "no DO blocks / functions": !/\bDO\b\s|CREATE (OR REPLACE )?FUNCTION/i.test(written),
  "no destructive statements": !/DROP (TABLE|COLUMN)|TRUNCATE|DELETE FROM|UPDATE\s+\w+\s+SET/i.test(written),
};

console.log(`\nWrote ${path}`);
console.log(`  dollar signs          : ${dollars} (expect 0)`);
for (const [label, ok] of Object.entries(checks)) {
  console.log(`  ${ok ? "ok    " : "FAILED"} ${label}`);
}
const ok = dollars === 0 && Object.values(checks).every(Boolean);
console.log(ok ? "\nOK — safe to run in the SQL editor.\n" : "\nBROKEN — do not run.\n");
process.exit(ok ? 0 : 1);
