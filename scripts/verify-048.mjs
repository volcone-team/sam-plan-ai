/**
 * Is migration 048 (the yearly onboarding booking link) applied?
 *
 * READ-ONLY. One SELECT on the app_settings singleton. Writes nothing and does
 * not apply anything.
 *
 * Usage: node scripts/verify-048.mjs
 */
import { createClient } from "@supabase/supabase-js";
import { readFileSync } from "node:fs";

for (const line of readFileSync(".env.local", "utf8").split("\n")) {
  const m = line.match(/^\s*([A-Z0-9_]+)\s*=\s*(.*)\s*$/);
  if (m) process.env[m[1]] ??= m[2].replace(/^["']|["']$/g, "");
}

const db = createClient(
  process.env.NEXT_PUBLIC_SUPABASE_URL,
  process.env.SUPABASE_SERVICE_ROLE_KEY
);

console.log("\nYearly onboarding booking link (migration 048)\n");

const { data, error } = await db
  .from("app_settings")
  .select("id, onboarding_call_url, onboarding_call_url_yearly")
  .eq("id", "global")
  .maybeSingle();

if (error) {
  console.log("  MISSING  app_settings.onboarding_call_url_yearly");
  console.log(`           ${error.message}`);
  console.log(
    "\nmigration not applied — run supabase/migrations/048_yearly_booking_link.sql\n" +
    "in the Supabase SQL editor (generated by scripts/gen-migration-048.mjs).\n" +
    "Until then every customer gets the monthly link, which is what they got before.\n"
  );
  process.exit(1);
}

if (!data) {
  console.log("  ok       column exists, but there is no 'global' app_settings row.");
} else {
  console.log(`  ok       app_settings.onboarding_call_url         = ${data.onboarding_call_url ?? "(not set)"}  (monthly, trials)`);
  console.log(`  ok       app_settings.onboarding_call_url_yearly  = ${data.onboarding_call_url_yearly ?? "(not set — yearly uses the monthly link)"}`);
}
console.log("\nApplied.\n");
