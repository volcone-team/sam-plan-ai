/**
 * Is migration 044 (the GoHighLevel outbox) applied?
 *
 * READ-ONLY. Four SELECTs: one ghl_events row to prove the table and its key
 * columns exist, one profiles row for the two login-state columns, the
 * app_settings singleton for the two switches, and a head count of pending
 * outbox rows. Writes nothing, enqueues nothing, and does not apply anything.
 *
 * Exits 1 when the migration is not applied.
 *
 * Usage: node scripts/verify-044.mjs
 */
import { createClient } from "@supabase/supabase-js";
import { readFileSync } from "node:fs";

for (const line of readFileSync(".env.local", "utf8").split("\n")) {
  const m = line.match(/^\s*([A-Z0-9_]+)\s*=\s*(.*)\s*$/);
  if (m) process.env[m[1]] ??= m[2].replace(/^["']|["']$/g, "");
}

const db = createClient(
  process.env.NEXT_PUBLIC_SUPABASE_URL,
  process.env.SUPABASE_SERVICE_ROLE_KEY
);

console.log("\nGoHighLevel outbox (migration 044)\n");

let outboxOk = false;
let profilesOk = false;
let settingsOk = false;

// ---- 1. ghl_events: the table and the columns the drain depends on ----
{
  const { error } = await db
    .from("ghl_events")
    .select(
      "id, company_id, user_id, contact_email, sub_account, event_type, " +
        "tags_add, tags_remove, payload, status, attempts, last_error, " +
        "next_attempt_at, dedupe_key, created_at, delivered_at"
    )
    .limit(1);

  if (error) {
    console.log("  MISSING  table ghl_events (or one of its columns)");
    console.log(`           ${error.message}`);
  } else {
    outboxOk = true;
    console.log("  ok       ghl_events with all 16 columns");
  }
}

// ---- 2. profiles: the login throttle and the one-shot first-login stamp ----
{
  const { error } = await db
    .from("profiles")
    .select("id, ghl_last_login_event_at, ghl_first_login_at")
    .limit(1);

  if (error) {
    console.log("  MISSING  profiles.ghl_last_login_event_at / ghl_first_login_at");
    console.log(`           ${error.message}`);
  } else {
    profilesOk = true;
    console.log("  ok       profiles.ghl_last_login_event_at, ghl_first_login_at");
  }
}

// ---- 3. app_settings: the two switches, and their CURRENT values ----
{
  const { data, error } = await db
    .from("app_settings")
    .select("id, ghl_enabled, ghl_dry_run")
    .eq("id", "global")
    .maybeSingle();

  if (error) {
    console.log("  MISSING  app_settings.ghl_enabled / ghl_dry_run");
    console.log(`           ${error.message}`);
  } else {
    settingsOk = true;
    if (!data) {
      console.log(
        "  ok       columns exist, but there is no 'global' app_settings row " +
          "(integration reads as OFF)."
      );
    } else {
      console.log(`  ok       app_settings.ghl_enabled = ${data.ghl_enabled}`);
      console.log(`  ok       app_settings.ghl_dry_run = ${data.ghl_dry_run}`);
    }
  }
}

// ---- 4. What is sitting in the outbox ----
if (outboxOk) {
  const counts = {};
  for (const status of ["pending", "delivered", "failed", "skipped"]) {
    const { count } = await db
      .from("ghl_events")
      .select("id", { count: "exact", head: true })
      .eq("status", status);
    counts[status] = count ?? "?";
  }

  const due = await db
    .from("ghl_events")
    .select("id", { count: "exact", head: true })
    .eq("status", "pending")
    .lte("next_attempt_at", new Date().toISOString());

  console.log("");
  console.log(`  pending                      : ${counts.pending}  (due now: ${due.count ?? "?"})`);
  console.log(`  delivered                    : ${counts.delivered}`);
  console.log(`  failed                       : ${counts.failed}`);
  console.log(`  skipped (contact not found)  : ${counts.skipped}`);
}

if (outboxOk && profilesOk && settingsOk) {
  console.log("\nApplied.\n");
} else {
  console.log(
    "\nmigration not applied — run supabase/migrations/044_ghl_outbox.sql\n" +
      "in the Supabase SQL editor (generated by scripts/gen-migration-044.mjs).\n" +
      "Applying it changes no behaviour on its own: ghl_enabled defaults FALSE\n" +
      "and ghl_dry_run defaults TRUE, so nothing reaches GoHighLevel until the\n" +
      "owner turns the integration on and then turns the dry run off.\n"
  );
  process.exit(1);
}
