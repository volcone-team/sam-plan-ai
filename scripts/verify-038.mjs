/**
 * Is migration 038 (SAM University) applied, seeded and locked down?
 *
 * Checks:
 *   1. The three tables exist (service role).
 *   2. Category and resource counts, and resources by access (free / Pro /
 *      other plans / no plan at all = admin-only).
 *   3. RLS: an ANON-key select on each table returns 0 rows or an error. A row
 *      coming back here means a policy exposes resource urls directly.
 *
 * Read-only. Usage: node scripts/verify-038.mjs
 */

import { createClient } from "@supabase/supabase-js";
import { readFileSync } from "node:fs";

for (const line of readFileSync(".env.local", "utf8").split("\n")) {
  const m = line.match(/^\s*([A-Z0-9_]+)\s*=\s*(.*)\s*$/);
  if (m) process.env[m[1]] ??= m[2].replace(/^["']|["']$/g, "");
}

const url = process.env.NEXT_PUBLIC_SUPABASE_URL;
const db = createClient(url, process.env.SUPABASE_SERVICE_ROLE_KEY);
const anon = createClient(url, process.env.NEXT_PUBLIC_SUPABASE_ANON_KEY, {
  auth: { persistSession: false },
});

const TABLES = ["university_categories", "university_resources", "university_resource_plans"];

console.log("\nSAM University (migration 038)\n");

let missing = false;
for (const table of TABLES) {
  // NOT a head:true count — a HEAD request against a missing table comes back
  // with no error body, which reads as "exists". A real select reports it.
  const { error } = await db.from(table).select("*").limit(1);
  if (error) {
    console.log(`  MISSING  ${table}  — ${error.message}`);
    missing = true;
  } else {
    console.log(`  ok       ${table}`);
  }
}

if (missing) {
  console.log(
    "\nmigration not applied — run supabase/migrations/038_sam_university.sql\n" +
    "in the Supabase SQL editor (generated by scripts/gen-migration-038.mjs).\n"
  );
  process.exit(1);
}

// ---------------------------------------------------------------
// Counts
// ---------------------------------------------------------------
const [{ data: categories }, { data: resources }, { data: links }, { data: plans }] =
  await Promise.all([
    db.from("university_categories").select("id, slug, name, is_published").order("display_order"),
    db.from("university_resources").select("id, slug, category_id, status, is_free"),
    db.from("university_resource_plans").select("resource_id, plan_id"),
    db.from("subscription_plans").select("id, name"),
  ]);

const planName = new Map((plans ?? []).map((p) => [p.id, p.name]));
const plansByResource = new Map();
for (const l of links ?? []) {
  const list = plansByResource.get(l.resource_id) ?? [];
  list.push(planName.get(l.plan_id) ?? l.plan_id);
  plansByResource.set(l.resource_id, list);
}

const rows = resources ?? [];
let free = 0, pro = 0, other = 0, adminOnly = 0;
for (const r of rows) {
  const names = plansByResource.get(r.id) ?? [];
  if (r.is_free) free++;
  else if (names.length === 0) adminOnly++;
  else if (names.length === 1 && names[0] === "Pro") pro++;
  else other++;
}

const byStatus = rows.reduce((acc, r) => ({ ...acc, [r.status]: (acc[r.status] ?? 0) + 1 }), {});

console.log(`\n  categories : ${(categories ?? []).length} (seed: 5)`);
for (const c of categories ?? []) {
  const n = rows.filter((r) => r.category_id === c.id).length;
  console.log(`    ${c.is_published ? "      " : "hidden"} ${c.slug.padEnd(24)} ${n} resource(s)`);
}
console.log(`  resources  : ${rows.length} (seed: 15)`);
console.log(`    by status: ${JSON.stringify(byStatus)}`);
console.log(`    free       : ${free} (seed: 3)`);
console.log(`    Pro only   : ${pro} (seed: 12)`);
console.log(`    other plans: ${other}`);
console.log(`    admin-only : ${adminOnly}${adminOnly ? "  (not free, no plans — was the Pro plan missing at seed time?)" : ""}`);

// ---------------------------------------------------------------
// RLS — the anon key must see nothing.
// ---------------------------------------------------------------
console.log("\n  RLS (anon key):");
let leaked = false;
for (const table of TABLES) {
  const { data, error } = await anon.from(table).select("*").limit(5);
  if (error) {
    console.log(`    ok       ${table}  — refused (${error.message})`);
  } else if ((data ?? []).length === 0) {
    console.log(`    ok       ${table}  — 0 rows`);
  } else {
    console.log(`    LEAK     ${table}  — anon read ${data.length} row(s)`);
    leaked = true;
  }
}

if (leaked) {
  console.log("\nFAILED — a policy exposes SAM University rows to anon. Remove it.\n");
  process.exit(1);
}

console.log("\nApplied.\n");
