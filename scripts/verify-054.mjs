/**
 * Is migration 054 (raw "Start Date" / "Event Date" workbook cells) applied?
 *
 * READ-ONLY. Selects the two new wb_initiative_library columns and reports
 * how many rows carry a value, so it also says whether the workbook has been
 * re-uploaded since. Writes nothing.
 *
 * Exits 1 when the columns are missing.
 *
 * Usage: node scripts/verify-054.mjs
 */
import { createClient } from "@supabase/supabase-js";
import { readFileSync } from "node:fs";
for (const line of readFileSync(".env.local", "utf8").split("\n")) {
  const m = line.match(/^\s*([A-Z0-9_]+)\s*=\s*(.*)\s*$/);
  if (m) process.env[m[1]] ??= m[2].replace(/^["']|["']$/g, "");
}
const db = createClient(process.env.NEXT_PUBLIC_SUPABASE_URL, process.env.SUPABASE_SERVICE_ROLE_KEY);
console.log("\nRaw Start Date / Event Date cells (migration 054)\n");
const { data, error } = await db
  .from("wb_initiative_library")
  .select("initiative_key, start_date_raw, event_date_raw");
if (error) {
  console.log("  MISSING  wb_initiative_library.start_date_raw / event_date_raw");
  console.log(`           ${error.message}`);
  console.log(
    "\nmigration not applied — run supabase/migrations/054_workbook_date_flags.sql\n" +
      "in the Supabase SQL editor (generated by scripts/gen-migration-054.mjs).\n" +
      "Until then every record asks for both dates, and an upload stores the\n" +
      "library without these two cells (src/lib/workbook/ingest.ts).\n"
  );
  process.exit(1);
}
const rows = data ?? [];
const filled = (k) => rows.filter((r) => typeof r[k] === "string" && r[k].trim() !== "").length;
console.log("  ok       wb_initiative_library.start_date_raw, event_date_raw");
console.log(`           ${rows.length} library rows; start_date_raw filled on ${filled("start_date_raw")}, event_date_raw on ${filled("event_date_raw")}`);
if (rows.length > 0 && filled("start_date_raw") === 0 && filled("event_date_raw") === 0) {
  console.log("\nApplied, but no row has the cells yet — re-upload the workbook at /admin/ai-workbook.\n");
} else {
  console.log("\nApplied.\n");
}
