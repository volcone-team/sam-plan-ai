/**
 * Is migration 043 (the onboarding call gate) applied?
 *
 * READ-ONLY. Three SELECTs: the app_settings singleton, one companies row to
 * prove the columns exist, and two head counts for the admin "who is waiting"
 * picture. Writes nothing and does not apply anything.
 *
 * Usage: node scripts/verify-043.mjs
 */
import { createClient } from "@supabase/supabase-js";
import { readFileSync } from "node:fs";

for (const line of readFileSync(".env.local", "utf8").split("\n")) {
  const m = line.match(/^\s*([A-Z0-9_]+)\s*=\s*(.*)\s*$/);
  if (m) process.env[m[1]] ??= m[2].replace(/^["']|["']$/g, "");
}

const db = createClient(
  process.env.NEXT_PUBLIC_SUPABASE_URL,
  process.env.SUPABASE_SERVICE_ROLE_KEY
);

console.log("\nCall before access (migration 043)\n");

let settingsOk = false;
let companiesOk = false;

// ---- 1. app_settings: the global switch and the booking link ----
{
  const { data, error } = await db
    .from("app_settings")
    .select("id, require_call_before_access, onboarding_call_url")
    .eq("id", "global")
    .maybeSingle();

  if (error) {
    console.log(`  MISSING  app_settings.require_call_before_access / onboarding_call_url`);
    console.log(`           ${error.message}`);
  } else {
    settingsOk = true;
    if (!data) {
      console.log("  ok       columns exist, but there is no 'global' app_settings row (gate reads as OFF).");
    } else {
      console.log(`  ok       app_settings.require_call_before_access = ${data.require_call_before_access}`);
      console.log(`  ok       app_settings.onboarding_call_url        = ${data.onboarding_call_url ?? "(not set)"}`);
    }
  }
}

// ---- 2. companies: the per-company gate state ----
{
  const { error } = await db
    .from("companies")
    .select("id, requires_call_unlock, portal_access_granted_at, portal_access_granted_by")
    .limit(1);

  if (error) {
    console.log("  MISSING  companies.requires_call_unlock / portal_access_granted_at / portal_access_granted_by");
    console.log(`           ${error.message}`);
  } else {
    companiesOk = true;
    console.log("  ok       companies.requires_call_unlock, portal_access_granted_at, portal_access_granted_by");
  }
}

// ---- 3. Who is waiting, who has been let in ----
if (companiesOk) {
  const waiting = await db
    .from("companies")
    .select("id", { count: "exact", head: true })
    .eq("requires_call_unlock", true)
    .is("portal_access_granted_at", null);

  const granted = await db
    .from("companies")
    .select("id", { count: "exact", head: true })
    .eq("requires_call_unlock", true)
    .not("portal_access_granted_at", "is", null);

  const total = await db
    .from("companies")
    .select("id", { count: "exact", head: true });

  console.log("");
  console.log(`  companies total              : ${total.count ?? "?"}`);
  console.log(`  waiting for their call       : ${waiting.count ?? "?"}  (flagged, no grant)`);
  console.log(`  unlocked after their call    : ${granted.count ?? "?"}  (flagged, granted)`);
  console.log(`  never gated                  : ${(total.count ?? 0) - (waiting.count ?? 0) - (granted.count ?? 0)}`);
}

if (settingsOk && companiesOk) {
  console.log("\nApplied.\n");
} else {
  console.log(
    "\nmigration not applied — run supabase/migrations/043_call_before_access.sql\n" +
    "in the Supabase SQL editor (generated by scripts/gen-migration-043.mjs).\n" +
    "Until then the gate reads as OFF and nobody is blocked, which is deliberate:\n" +
    "applying it changes nothing until the switch is turned on.\n"
  );
  process.exit(1);
}
