/**
 * Is migration 040 (library scores, industries, metrics; initiatives
 * library_key / metric_set) applied, and has the workbook been re-uploaded?
 *
 * Checks:
 *   1. Every new column can be selected (service role).
 *   2. How many library rows carry scores, industries, metrics text, variants.
 *
 * Read-only. Usage: node scripts/verify-040.mjs
 */
import { createClient } from "@supabase/supabase-js";
import { readFileSync } from "node:fs";

for (const line of readFileSync(".env.local", "utf8").split("\n")) {
  const m = line.match(/^\s*([A-Z0-9_]+)\s*=\s*(.*)\s*$/);
  if (m) process.env[m[1]] ??= m[2].replace(/^["']|["']$/g, "");
}
const db = createClient(process.env.NEXT_PUBLIC_SUPABASE_URL, process.env.SUPABASE_SERVICE_ROLE_KEY);

const COLUMNS = {
  wb_initiative_library: [
    "workbook_id", "base_key", "speed_score", "cost_score", "odds_score", "revenue_score",
    "ease_score", "score_total", "ideal_industries", "cta_options", "training", "metrics_raw", "metrics",
  ],
  initiatives: ["library_key", "metric_set"],
};

console.log("\nLibrary scores & metrics (migration 040)\n");
let missing = false;
for (const [table, columns] of Object.entries(COLUMNS)) {
  for (const column of columns) {
    // A real select (not head:true), so a missing column reports an error.
    const { error } = await db.from(table).select(column).limit(1);
    if (error) {
      console.log(`  MISSING  ${table}.${column}  — ${error.message}`);
      missing = true;
    } else {
      console.log(`  ok       ${table}.${column}`);
    }
  }
}

if (missing) {
  console.log(
    "\nmigration not applied — run supabase/migrations/040_library_scores_metrics.sql\n" +
    "in the Supabase SQL editor (generated by scripts/gen-migration-040.mjs),\n" +
    "then upload the workbook again at /admin/ai-workbook.\n"
  );
  const { count } = await db.from("wb_initiative_library").select("initiative_key", { count: "exact", head: true });
  console.log(`  library rows today: ${count ?? "?"} (none can carry scores yet)\n`);
  process.exit(1);
}

const { data, error } = await db
  .from("wb_initiative_library")
  .select("initiative_key, base_key, score_total, speed_score, ideal_industries, metrics_raw");
if (error) {
  console.log(`\n  could not read the library: ${error.message}\n`);
  process.exit(1);
}
const rows = data ?? [];
const n = (pred) => rows.filter(pred).length;
console.log(`\n  library rows          : ${rows.length}`);
console.log(`  with any score        : ${n((r) => r.speed_score !== null || r.score_total !== null)}`);
console.log(`  with all five (total) : ${n((r) => r.score_total !== null)}`);
console.log(`  with ideal industries : ${n((r) => (r.ideal_industries ?? []).length > 0)}`);
console.log(`  with metrics text     : ${n((r) => r.metrics_raw)}`);
console.log(`  variants (base_key)   : ${n((r) => r.base_key)}`);
if (rows.length > 0 && n((r) => r.score_total !== null || r.speed_score !== null) === 0) {
  console.log("\n  Applied, but no row has scores: upload the workbook again at /admin/ai-workbook.");
}
console.log("\nApplied.\n");
