/**
 * Is migration 041 (app_settings.recommendation_revenue_weight) applied?
 *
 * Read-only: one SELECT on the app_settings singleton.
 * Usage: node scripts/verify-041.mjs
 */
import { createClient } from "@supabase/supabase-js";
import { readFileSync } from "node:fs";

for (const line of readFileSync(".env.local", "utf8").split("\n")) {
  const m = line.match(/^\s*([A-Z0-9_]+)\s*=\s*(.*)\s*$/);
  if (m) process.env[m[1]] ??= m[2].replace(/^["']|["']$/g, "");
}

const db = createClient(process.env.NEXT_PUBLIC_SUPABASE_URL, process.env.SUPABASE_SERVICE_ROLE_KEY);

console.log("\nRecommendation revenue weight (migration 041)\n");

const { data, error } = await db
  .from("app_settings")
  .select("id, recommendation_revenue_weight")
  .eq("id", "global")
  .maybeSingle();

if (error) {
  console.log(`  MISSING  app_settings.recommendation_revenue_weight  — ${error.message}`);
  console.log(
    "\nmigration not applied — run supabase/migrations/041_recommendation_weight.sql\n" +
    "in the Supabase SQL editor (generated by scripts/gen-migration-041.mjs).\n" +
    "Until then the app ranks with weight 1 (equal weight).\n"
  );
  process.exit(1);
}

if (!data) {
  console.log("  ok       column exists, but there is no 'global' app_settings row (app uses 1).");
} else {
  console.log(`  ok       app_settings.recommendation_revenue_weight = ${data.recommendation_revenue_weight}`);
}
console.log("\nApplied.\n");
