/**
 * Is migration 051 (seven frequencies + raw workbook cells) applied?
 *
 * READ-ONLY. Selects the two new wb_initiative_library columns (limit 1) and
 * tries to read the three widened CHECK definitions through an optional
 * pg_get_constraintdef_by_name RPC. Inserts nothing: testing a CHECK by
 * writing a 'bi-weekly' row would touch customer tables on the one database
 * dev and production share. Where a CHECK cannot be read from here the
 * script says SKIP and prints the query to paste instead of guessing.
 *
 * Exits 1 when the columns are missing or a readable CHECK is still narrow.
 *
 * Usage: node scripts/verify-051.mjs
 */
import { createClient } from "@supabase/supabase-js";
import { readFileSync } from "node:fs";

for (const line of readFileSync(".env.local", "utf8").split("\n")) {
  const m = line.match(/^\s*([A-Z0-9_]+)\s*=\s*(.*)\s*$/);
  if (m) process.env[m[1]] ??= m[2].replace(/^["']|["']$/g, "");
}
const db = createClient(process.env.NEXT_PUBLIC_SUPABASE_URL, process.env.SUPABASE_SERVICE_ROLE_KEY);

const NEW_VALUES = ["bi-weekly", "bi-monthly", "semi-annually", "annually"];
const CONSTRAINTS = [
  "initiatives_repeat_frequency_check",
  "intake_initiatives_repeat_frequency_check",
  "initiative_library_config_allowed_frequencies_check",
];

console.log("\nSeven frequencies + raw workbook cells (migration 051)\n");

let columnsOk = false;
{
  const { error } = await db
    .from("wb_initiative_library")
    .select("initiative_key, allowed_kinds_raw, allowed_frequencies_raw")
    .limit(1);
  if (error) {
    console.log("  MISSING  wb_initiative_library.allowed_kinds_raw / allowed_frequencies_raw");
    console.log(`           ${error.message}`);
  } else {
    columnsOk = true;
    console.log("  ok       wb_initiative_library.allowed_kinds_raw, allowed_frequencies_raw");
  }
}

let checksOk = true;
let skipped = false;
for (const name of CONSTRAINTS) {
  const { data, error } = await db.rpc("pg_get_constraintdef_by_name", { conname: name });
  if (error || typeof data !== "string") {
    skipped = true;
    console.log(`  SKIP     ${name} (cannot read the catalog from here)`);
    continue;
  }
  const missing = NEW_VALUES.filter((v) => !data.includes(`'${v}'`));
  if (missing.length === 0) {
    console.log(`  ok       ${name} accepts all seven`);
  } else {
    checksOk = false;
    console.log(`  STALE    ${name} is missing ${missing.join(", ")}`);
    console.log(`           ${data}`);
  }
}
if (skipped) {
  console.log(
    "\n  Confirm the CHECKs by hand in the SQL editor:\n" +
      "    SELECT conname, pg_get_constraintdef(oid) FROM pg_constraint\n" +
      "     WHERE conname IN (" + CONSTRAINTS.map((c) => `'${c}'`).join(", ") + ");\n" +
      "  Each must list 'bi-weekly', 'bi-monthly', 'semi-annually' and 'annually',\n" +
      "  and no other CHECK on those columns may remain:\n" +
      "    SELECT conrelid::regclass, conname, pg_get_constraintdef(oid) FROM pg_constraint\n" +
      "     WHERE contype = 'c' AND (pg_get_constraintdef(oid) ILIKE '%repeat_frequency%'\n" +
      "                           OR pg_get_constraintdef(oid) ILIKE '%allowed_frequencies%');"
  );
}

if (columnsOk && checksOk) {
  console.log(skipped ? "\nColumns applied (CHECKs not verifiable from here).\n" : "\nApplied.\n");
} else {
  console.log(
    "\nmigration not applied — run supabase/migrations/051_frequencies_and_workbook_kinds.sql\n" +
      "in the Supabase SQL editor (generated by scripts/gen-migration-051.mjs).\n" +
      "Until then a new frequency written to a narrow CHECK is retried without it\n" +
      "(src/lib/initiatives/frequency-fallback.ts).\n"
  );
  process.exit(1);
}
