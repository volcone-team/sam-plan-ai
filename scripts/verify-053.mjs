import { createClient } from "@supabase/supabase-js";
import { readFileSync } from "node:fs";

for (const line of readFileSync(".env.local", "utf8").split("\n")) {
  const m = line.match(/^\s*([A-Z0-9_]+)\s*=\s*(.*)\s*$/);
  if (m) process.env[m[1]] ??= m[2].replace(/^["']|["']$/g, "");
}
const db = createClient(process.env.NEXT_PUBLIC_SUPABASE_URL, process.env.SUPABASE_SERVICE_ROLE_KEY);

console.log("\nCustomer industries Other text (migration 053)\n");

// A real select (not head:true), so a missing column reports an error.
const { error } = await db.from("planning_inputs").select("customer_industries_other").limit(1);
if (error) {
  console.log(`  MISSING  planning_inputs.customer_industries_other  — ${error.message}`);
  console.log(
    "\nmigration not applied — run supabase/migrations/053_customer_industries_other.sql\n" +
      "in the Supabase SQL editor (generated by scripts/gen-migration-053.mjs).\n" +
      "Until then the intake saves without this one answer.\n"
  );
  process.exit(1);
}
console.log("  ok       planning_inputs.customer_industries_other");

const { count } = await db
  .from("planning_inputs")
  .select("id", { count: "exact", head: true })
  .not("customer_industries_other", "is", null);
console.log(`  rows with it set: ${count ?? "?"}`);
console.log("\nApplied.\n");
