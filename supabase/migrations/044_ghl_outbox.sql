-- ============================================================
-- GOHIGHLEVEL OUTBOX
--
-- One row per intended GHL side effect: "add these tags to this contact in
-- this sub-account". Nothing in this migration talks to GHL; it only records
-- what should happen, so that delivery is a separate, retryable concern.
--
-- WHY AN OUTBOX AND NOT INLINE HTTP CALLS. The Stripe webhook is the only
-- writer of subscription state in this app, and its idempotency comes from an
-- insert into stripe_webhook_events: process the event once, return 2xx, never
-- see it again. If that handler called GHL inline, a GHL outage, a rate limit
-- or a slow network would make the handler non-2xx, Stripe would retry, and we
-- would be re-processing a PAYMENT event for the sake of a MARKETING side
-- effect. The blast radius of a marketing tag must never reach billing state.
-- Enqueueing is a local insert in the same transaction-ish path as the state
-- write; the drain retries on its own schedule and its failures cost nothing
-- but a tag.
--
-- The same argument applies to the other producers (intake completion, plan
-- generation, login): none of them should fail, block or slow down a user
-- request because a third-party CRM is having a bad day.
--
-- SECRETS AND LOCATION IDS ARE NOT IN THE DATABASE. The three GHL
-- sub-accounts are addressed by location id, and a location id pairs 1:1 with
-- the token that can write to it; storing one here would invite the pair to
-- drift apart and would put half a credential in the database and in every
-- backup. They live in env vars (task 3), named only, never valued, for the
-- record: GHL_APP_LOCATION_ID, GHL_APP_TOKEN, GHL_AYR_LOCATION_ID,
-- GHL_AYR_TOKEN, GHL_10X_LOCATION_ID, GHL_10X_TOKEN. The sub_account column
-- below is the SHORT NAME of a location, which the app maps to an id/token
-- pair at delivery time.
--
-- INERT UNTIL SWITCHED ON. app_settings.ghl_enabled defaults FALSE and
-- app_settings.ghl_dry_run defaults TRUE, exactly like
-- require_call_before_access in 043: applying this migration changes no
-- behaviour, and the first thing that happens after an admin enables the
-- integration is a dry run, not live writes into the client CRM.
--
-- GENERATED by scripts/gen-migration-044.mjs. Edit that, not this.
-- SAFE TO RE-RUN: every statement is guarded.
-- ============================================================

-- ------------------------------------------------------------
-- 1. ghl_events — the outbox itself.
--
-- uuid_generate_v4() and not gen_random_uuid(): the uuid-ossp extension is
-- created in migration 001 and every table from 001 to 037 that generates its
-- own id uses it (038/039 are the two outliers; the natural-key tables such as
-- app_settings 020 and initiative_settings 034 generate nothing at all).
-- Following the house majority, and 011 in particular,
-- which this table is otherwise shaped after.
--
-- EMAIL IS THE GHL JOIN KEY AND EMAIL IS REUSABLE IN THIS APP. A customer can
-- delete their account and sign up again with the same address, and a
-- different person can inherit a company mailbox. That reuse has already cost
-- us once: the billing reconcile looked a Stripe customer up by email with no
-- time bound and a recreated account adopted a deleted account subscription.
-- So contact_email is what we send to GHL, but it is NOT the identity of the
-- row: company_id and user_id are carried as well, and a queued row must be
-- re-checked against them before delivery rather than trusted because the
-- address still matches something.
-- ------------------------------------------------------------
CREATE TABLE IF NOT EXISTS ghl_events (
  id UUID PRIMARY KEY DEFAULT uuid_generate_v4(),

  -- Nullable: some events are about a PERSON (first login, login trigger,
  -- marketing suppression) and have no company context worth asserting.
  company_id UUID REFERENCES companies(id) ON DELETE CASCADE,
  -- Nullable, and SET NULL rather than CASCADE: a delivered row is a record of
  -- something we really did to the client CRM, and deleting the account must
  -- not erase that history. Mirrors generation_events.user_id from 011.
  user_id UUID REFERENCES profiles(id) ON DELETE SET NULL,

  contact_email TEXT NOT NULL,

  -- Which GHL location this event targets. The app sub-account carries the
  -- lifecycle tags; ayr and 10x carry only the suppression tag.
  sub_account TEXT NOT NULL
    CHECK (sub_account IN ('app', 'ayr', '10x')),

  event_type TEXT NOT NULL
    CHECK (event_type IN (
      'buyer_state',
      'founder',
      'cancellation',
      'finished_intake',
      'plan_generated',
      'first_login',
      'login_trigger',
      'marketing_suppression'
    )),

  -- THE RESOLVED TAG NAMES, not the inputs they were derived from.
  tags_add TEXT[] NOT NULL DEFAULT '{}',
  tags_remove TEXT[] NOT NULL DEFAULT '{}',

  payload JSONB NOT NULL DEFAULT '{}',

  status TEXT NOT NULL DEFAULT 'pending'
    CHECK (status IN ('pending', 'delivered', 'failed', 'skipped')),
  attempts INT NOT NULL DEFAULT 0,
  last_error TEXT,
  next_attempt_at TIMESTAMPTZ NOT NULL DEFAULT now(),

  dedupe_key TEXT,

  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  delivered_at TIMESTAMPTZ
);

COMMENT ON TABLE ghl_events IS
  'Outbox of intended GoHighLevel side effects. Producers (the Stripe webhook, intake, plan generation, login) only INSERT here; a separate drain delivers. Keeps a third-party CRM outage from making the Stripe webhook non-2xx and triggering a retry of a payment event. Operational data, service-role only.';

COMMENT ON COLUMN ghl_events.company_id IS
  'Company the event is about, or NULL for person-level events (first login, login trigger, marketing suppression). CASCADE: an enqueued event for a deleted company is meaningless.';

COMMENT ON COLUMN ghl_events.user_id IS
  'Person the event is about. ON DELETE SET NULL so the record of what we sent survives the account, as in generation_events (011).';

COMMENT ON COLUMN ghl_events.contact_email IS
  'The GHL join key - GHL has no concept of our ids. NOT an identity: email is reusable in this app (a deleted account can be recreated on the same address, and that reuse already caused the billing reconcile to adopt a deleted account subscription), so a queued row must be re-checked against company_id/user_id before delivery and never matched on email alone.';

COMMENT ON COLUMN ghl_events.sub_account IS
  'Target GHL location, by short name: app (SAM Plan AI, all lifecycle tags), ayr, 10x (marketing, suppression tag only). The location id and token for each live in env vars, never here.';

COMMENT ON COLUMN ghl_events.event_type IS
  'What happened, not what to write (the tags columns say that). buyer_state: purchase or tier change - one buyer tag added, the others removed. founder: founding-member cohort, add only. cancellation: subscription ended. finished_intake / plan_generated: lifecycle milestones. first_login: one-shot, guarded by profiles.ghl_first_login_at. login_trigger: fires on login as a workflow trigger, throttled by profiles.ghl_last_login_event_at. marketing_suppression: the Customer - SAM Plan AI tag in the ayr / 10x accounts, added when they start paying and removed when they stop.';

COMMENT ON COLUMN ghl_events.tags_add IS
  'RESOLVED tag strings from the contract in src/lib/ghl/tags.ts, snapshotted at enqueue. Deliberately not re-derived at delivery time: buyer tags contain the admin-editable subscription_plans.name, and a plan renamed between enqueue and delivery must not silently change what gets written to the CRM - the tag that matches the workflow the client built is the one that was true when the event happened.';

COMMENT ON COLUMN ghl_events.tags_remove IS
  'Tags to clear, resolved at enqueue for the same reason as tags_add. Sent unconditionally: the GHL remove-tag call is a no-op for a tag the contact does not have, so there is nothing to gain by reading the contact first and a race to lose by it.';

COMMENT ON COLUMN ghl_events.payload IS
  'Context for debugging and for any later custom-field sync (plan name, cycle, source route, counts). MUST NOT CONTAIN SECRETS: no tokens, no location ids, no session data. Readable by anyone with database or backup access.';

COMMENT ON COLUMN ghl_events.status IS
  'pending: not yet delivered, eligible once next_attempt_at passes. delivered: GHL accepted it (or dry run recorded it). failed: terminal after the retry budget, see last_error. skipped: TERMINAL AND LEGITIMATE, not a failure - the contact does not exist in that sub-account, which is normal for the ayr / 10x suppression tag, so it must not be retried and must not show up as an error on the admin screen.';

COMMENT ON COLUMN ghl_events.attempts IS
  'Delivery attempts so far. Drives the backoff written into next_attempt_at and the cutoff to status = failed. The policy lives in app code, not here.';

COMMENT ON COLUMN ghl_events.next_attempt_at IS
  'Not before this time. Defaults to now() so a fresh row is immediately claimable; the drain pushes it forward on retry.';

COMMENT ON COLUMN ghl_events.dedupe_key IS
  'Stable identity of the LOGICAL event, e.g. a Stripe event id plus the tag intent, or user plus day for the login trigger. Enforced by uq_ghl_events_dedupe, which is partial over status IN (pending, delivered): an event that is queued or already written must not be enqueued twice, but a failed or skipped row may be re-enqueued with the same key, because both are states an operator legitimately retries later (the retry budget was exhausted during an outage, or the contact did not exist in that sub-account yet). NULL for one-off and ad-hoc rows, which are never deduped - same convention as app_notifications.dedupe_key (013).';

COMMENT ON COLUMN ghl_events.delivered_at IS
  'When the row reached a terminal state, delivered or skipped. NULL while pending or failed-and-retriable.';

-- ------------------------------------------------------------
-- 2. Indexes.
--
-- THE CLAIM QUERY is the only hot read: status = pending AND next_attempt_at
-- <= now() ORDER BY created_at. PARTIAL ON pending, because this table only
-- grows and a delivered row would sit in a full index forever, inflating it
-- for a query that can never return it; the pending set is the small, churning
-- tip. Columns in (next_attempt_at, created_at) order so the range predicate
-- leads and the ordering is still satisfied from the index for the rows that
-- pass it.
--
-- NOT INDEXED, on purpose:
--   contact_email  - ad-hoc "what did we send this person" debugging by an
--                    admin, rare and happy with a scan. A useful index would
--                    have to be on lower(contact_email) to match how GHL
--                    treats addresses, which is a second decision better made
--                    when the admin screen actually needs it.
--   status / event_type - a handful of distinct values over a table Postgres
--                    will scan anyway, and the one selective case (pending)
--                    is already served by the partial index above.
--   delivered_at   - nothing orders or filters by it; it is read per row.
-- ------------------------------------------------------------
CREATE INDEX IF NOT EXISTS idx_ghl_events_claim
  ON ghl_events(next_attempt_at, created_at)
  WHERE status = 'pending';

-- The admin "what has this company triggered" view, newest first. Cheap, and
-- the alternative is a full scan of a table that grows with every login.
CREATE INDEX IF NOT EXISTS idx_ghl_events_company_created
  ON ghl_events(company_id, created_at DESC);

-- Dedupe. Scoped BY SUB-ACCOUNT because one logical change (a customer starts
-- paying) legitimately produces the same intent against app, ayr and 10x, and
-- those are three different contacts in three different locations.
CREATE UNIQUE INDEX IF NOT EXISTS uq_ghl_events_dedupe
  ON ghl_events(sub_account, dedupe_key)
  WHERE dedupe_key IS NOT NULL AND status IN ('pending', 'delivered');

-- ------------------------------------------------------------
-- 3. RLS: ENABLED, with NO policies at all.
--
-- With RLS on and no policies, anon and authenticated read zero rows; the
-- service role bypasses RLS, which is how the drain and the admin screen get
-- at the data (both already behind requireAdmin()).
--
-- THIS IS DELIBERATELY UNLIKE generation_events (011), which grants members a
-- SELECT on their own company rows. That table holds counts of their own AI
-- generations - their data, about them, useful to show them. This one holds
-- email addresses and tag intent spanning THREE marketing sub-accounts that
-- belong to the client, not to the customer. A member-scoped policy would
-- still be the wrong shape: the person-level rows have company_id NULL, so
-- "your company rows" cannot express them, and nothing in the product ever
-- shows a customer which CRM tags we hold about them. No policy is simpler to
-- reason about than a policy nobody uses.
-- ------------------------------------------------------------
ALTER TABLE ghl_events ENABLE ROW LEVEL SECURITY;

-- ------------------------------------------------------------
-- 4. profiles — login event state.
--
-- ON PROFILES AND NOT COMPANIES, because a GHL contact is a PERSON. A company
-- can have several team members who each log in and each have their own
-- contact record in GHL; hanging the throttle off the company would mean the
-- first member to log in each day silenced the rest, and would make the
-- one-shot first-login tag fire for exactly one of them.
--
-- The login tag is a WORKFLOW TRIGGER, not a state flag, and there is no login
-- event in this app today - only a stream of authenticated requests. Without a
-- throttle, every page load would be a GHL write, which would both hammer
-- their API and continuously reset the inactivity workflow that the 30 / 60 /
-- 90 day win-back emails hang off, so nobody would ever be counted inactive.
--
-- NO INDEX on either column, for the reason 043 gives about companies: these
-- are read by primary key on the signed-in profile, never scanned. If a cron
-- ever sweeps for stale logins it will want one; it does not exist yet.
-- ------------------------------------------------------------
ALTER TABLE profiles
  ADD COLUMN IF NOT EXISTS ghl_last_login_event_at TIMESTAMPTZ,
  ADD COLUMN IF NOT EXISTS ghl_first_login_at TIMESTAMPTZ;

COMMENT ON COLUMN profiles.ghl_last_login_event_at IS
  'When we last enqueued the login-trigger event for this person. The throttle: app code enqueues only if this is older than the window (24h by default) and then stamps it. The window is NOT encoded here - a default in SQL could not be changed without another hand-run migration.';

COMMENT ON COLUMN profiles.ghl_first_login_at IS
  'First login we ever recorded for this person, so the one-shot first-login tag is idempotent without querying the outbox. NULL means it has never fired; set once and never cleared, which also keeps it correct after outbox rows are pruned.';

-- ------------------------------------------------------------
-- 5. app_settings — the operational switches.
--
-- app_settings is the singleton from migration 020 (id = global).
--
-- TWO SWITCHES, NOT ONE, because "is the integration live" and "is it allowed
-- to write" are different questions. Turning the integration on with dry run
-- still on exercises the whole path - producers enqueue, the drain claims,
-- resolves the sub-account, logs the call it would have made and marks the row
-- delivered - against the real database and the real event stream, with the
-- client CRM untouched. A single flag would force the first live test to be a
-- live write into a CRM full of their customers.
-- ------------------------------------------------------------
ALTER TABLE app_settings
  ADD COLUMN IF NOT EXISTS ghl_enabled BOOLEAN NOT NULL DEFAULT FALSE,
  ADD COLUMN IF NOT EXISTS ghl_dry_run BOOLEAN NOT NULL DEFAULT TRUE;

COMMENT ON COLUMN app_settings.ghl_enabled IS
  'Master off switch for the GoHighLevel integration. FALSE: producers enqueue nothing and the drain does nothing, so applying migration 044 changes no behaviour until the owner turns it on deliberately - same stance as require_call_before_access in 043. Default FALSE.';

COMMENT ON COLUMN app_settings.ghl_dry_run IS
  'When TRUE the drain resolves and logs the calls it would make, marks the rows delivered and contacts GHL not at all. Default TRUE so the first thing that happens after enabling the integration is a dry run rather than live writes into the client CRM. Set FALSE only once a dry run looks right.';
