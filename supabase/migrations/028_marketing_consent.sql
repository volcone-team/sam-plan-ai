-- ============================================================
-- MARKETING COMMUNICATIONS CONSENT
--
-- Captured at registration. Stored on `profiles` rather than `companies`
-- because consent is given by a PERSON, not an organisation: two colleagues on
-- the same account can answer differently.
--
-- THREE STATES, which is why the column is nullable:
--   TRUE  -> opted in
--   FALSE -> explicitly declined
--   NULL  -> never asked
--
-- NULL matters. Every profile that existed before this migration was never
-- shown the checkbox, and defaulting them to FALSE would record a refusal they
-- never gave; defaulting to TRUE would invent consent, which is worse. NULL is
-- the only honest value, and it lets a later campaign tell "declined" from
-- "unknown".
--
-- The timestamp is separate because consent must be evidenced: "when did they
-- agree" cannot be derived from the boolean.
--
-- GENERATED by scripts/gen-migration-028.mjs. Edit that, not this.
-- SAFE TO RE-RUN: every statement is guarded.
-- ============================================================

ALTER TABLE profiles
  ADD COLUMN IF NOT EXISTS marketing_consent BOOLEAN,
  ADD COLUMN IF NOT EXISTS marketing_consent_at TIMESTAMPTZ;

COMMENT ON COLUMN profiles.marketing_consent IS
  'TRUE opted in, FALSE declined, NULL never asked.';

COMMENT ON COLUMN profiles.marketing_consent_at IS
  'When consent was given or withdrawn. Evidence needs its own timestamp.';

-- Partial index: the only query is "who may be emailed", a small subset.
CREATE INDEX IF NOT EXISTS idx_profiles_marketing_consent
  ON profiles(marketing_consent) WHERE marketing_consent = TRUE;

-- ------------------------------------------------------------
-- Carry the checkbox through signup.
--
-- The profile is created by a TRIGGER, not by application code, so the consent
-- answer travels in raw_user_meta_data and is read here. Writing it from the
-- client afterwards would be a second round trip that can fail on its own,
-- leaving consent silently back at "never asked" — the one state that must not
-- be fabricated.
--
-- Everything else is UNCHANGED from migration 023, restated in full because
-- CREATE OR REPLACE cannot patch a function body and a partial redefinition
-- would drop the trial setup.
-- ------------------------------------------------------------
CREATE OR REPLACE FUNCTION public.handle_new_user()
RETURNS TRIGGER
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
  new_company_id UUID;
  v_company_name TEXT;
  v_first TEXT;
  v_last TEXT;
  v_trial_enabled BOOLEAN;
  v_trial_days INT;
  v_trial_plan UUID;
  v_consent BOOLEAN;
BEGIN
  v_first := COALESCE(NEW.raw_user_meta_data->>'first_name', '');
  v_last  := COALESCE(NEW.raw_user_meta_data->>'last_name', '');
  v_company_name := COALESCE(
    NULLIF(NEW.raw_user_meta_data->>'company_name', ''),
    v_first || E'\x27' || 's Company'
  );

  -- Absent metadata stays NULL rather than becoming FALSE. A user created by
  -- an admin or team invite never sees the checkbox, so recording a refusal
  -- for them would be inventing an answer. Only an explicit true/false from
  -- the signup form is a real answer.
  v_consent := CASE
    WHEN NEW.raw_user_meta_data->>'marketing_consent' = 'true'  THEN TRUE
    WHEN NEW.raw_user_meta_data->>'marketing_consent' = 'false' THEN FALSE
    ELSE NULL
  END;

  INSERT INTO companies (name, description, fiscal_year, planning_year, currency)
  VALUES (
    v_company_name, '',
    EXTRACT(YEAR FROM NOW())::INT,
    EXTRACT(YEAR FROM NOW())::INT,
    'USD'
  )
  RETURNING id INTO new_company_id;

  INSERT INTO profiles (
    id, company_id, email, first_name, last_name, role, is_admin,
    marketing_consent, marketing_consent_at
  )
  VALUES (
    NEW.id, new_company_id, NEW.email, v_first, v_last, 'owner', FALSE,
    v_consent,
    CASE WHEN v_consent IS NULL THEN NULL ELSE NOW() END
  );

  INSERT INTO annual_plans (
    company_id, year, baseline_revenue, stretch_revenue, operating_budget, status
  )
  VALUES (new_company_id, EXTRACT(YEAR FROM NOW())::INT, 0, 0, 0, 'draft');

  SELECT
    COALESCE(trial_enabled, TRUE),
    COALESCE(NULLIF(trial_days, 0), 14),
    trial_plan_id
  INTO v_trial_enabled, v_trial_days, v_trial_plan
  FROM app_settings WHERE id = 'global';

  v_trial_enabled := COALESCE(v_trial_enabled, TRUE);
  v_trial_days    := COALESCE(v_trial_days, 14);
  v_trial_plan    := COALESCE(
    v_trial_plan,
    (SELECT id FROM subscription_plans WHERE is_default ORDER BY display_order LIMIT 1)
  );

  INSERT INTO subscriptions (
    company_id, tier, status, billing_cycle, plan_id,
    is_trial_active, trial_ends_at, start_date
  )
  VALUES (
    new_company_id,
    'starter',
    CASE WHEN v_trial_enabled THEN 'trial' ELSE 'cancelled' END,
    'monthly',
    v_trial_plan,
    v_trial_enabled,
    CASE WHEN v_trial_enabled THEN NOW() + (v_trial_days || ' days')::INTERVAL ELSE NULL END,
    NOW()
  );

  RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS on_auth_user_created ON auth.users;
CREATE TRIGGER on_auth_user_created
  AFTER INSERT ON auth.users
  FOR EACH ROW
  EXECUTE FUNCTION public.handle_new_user();
