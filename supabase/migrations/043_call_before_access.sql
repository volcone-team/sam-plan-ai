-- ============================================================
-- CALL BEFORE ACCESS
--
-- New customers must not land in the portal straight after paying. The order
-- becomes: sign up -> pick plan -> pay -> thank-you page with a "Book a call
-- with us" button -> an admin opens the portal after the call has happened.
--
-- THIS IS NOT BILLING. It is deliberately separate from the comp/grant that
-- src/lib/billing/entitlement.ts decides: a company can be unlocked and still
-- owe money, or be comped and still be waiting for its call. Two independent
-- gates, two independent columns, so neither can silently undo the other.
--
-- WHY A PER-COMPANY FLAG AND NOT JUST THE GLOBAL SWITCH: turning the feature
-- on must not lock out the customers who are already using the product. The
-- switch is therefore only read at COMPANY CREATION and snapshotted onto the
-- new row (src/lib/access/call-gate-settings.ts). Every row that exists when
-- this migration runs gets FALSE from the DEFAULT, which is exactly why
-- existing customers are never blocked.
--
-- Until this is applied the app reads the switch as OFF and nobody is gated:
-- see loadCallGateSettings, which treats a missing column as off rather than
-- failing. Applying it changes nothing on its own — the switch still has to
-- be turned on deliberately.
--
-- GENERATED by scripts/gen-migration-043.mjs. Edit that, not this.
-- SAFE TO RE-RUN: every statement is guarded.
-- ============================================================

-- ------------------------------------------------------------
-- 1. app_settings — the global switch and the booking link.
--
-- app_settings is the singleton from migration 020 (id = 'global').
--
-- onboarding_call_url is a NEW column rather than a reuse of migration 033's
-- retention_reset_call_url / retention_strategy_call_url. Those two are the
-- CANCELLATION flow's calendars: whoever sets one is choosing which screen a
-- leaving customer sees, and an empty value hides that screen. Pointing the
-- onboarding gate at the same column would mean an admin pasting the new
-- customer calendar silently re-pointed the save-the-cancellation screens, and
-- clearing one to hide a retention screen would strand every paying new
-- customer with no way to book. Different call, different audience, different
-- lifecycle: its own column.
-- ------------------------------------------------------------
ALTER TABLE app_settings
  ADD COLUMN IF NOT EXISTS require_call_before_access BOOLEAN NOT NULL DEFAULT FALSE,
  ADD COLUMN IF NOT EXISTS onboarding_call_url TEXT;

COMMENT ON COLUMN app_settings.require_call_before_access IS
  'Global switch for the onboarding call gate. When TRUE, companies created from then on are stamped companies.requires_call_unlock and cannot use the portal until an admin grants access. Read only at company creation, never as a live gate, so switching it on cannot lock out existing customers. Default FALSE.';

COMMENT ON COLUMN app_settings.onboarding_call_url IS
  'Booking link (GHL calendar) for the new-customer onboarding call, shown on the thank-you page. Any https URL; empty renders an honest fallback instead of a dead button. NOT the cancellation calendars - those are retention_reset_call_url and retention_strategy_call_url from migration 033.';

-- ------------------------------------------------------------
-- 2. companies — the per-company gate state.
--
-- NO INDEX, on purpose. The obvious candidate is requires_call_unlock for the
-- admin "who is waiting" list, and it would not be used: the column is a
-- two-value boolean on a table of tens to hundreds of rows, which Postgres
-- will sequentially scan regardless, and /admin/companies already reads the
-- whole table with an exact count and paginates in the API rather than
-- filtering in SQL. An index here would cost writes on every signup and buy
-- nothing. Revisit if the admin list ever grows a server-side WHERE on this
-- column over a much larger table.
-- ------------------------------------------------------------
ALTER TABLE companies
  ADD COLUMN IF NOT EXISTS requires_call_unlock BOOLEAN NOT NULL DEFAULT FALSE,
  ADD COLUMN IF NOT EXISTS portal_access_granted_at TIMESTAMPTZ,
  ADD COLUMN IF NOT EXISTS portal_access_granted_by UUID;

COMMENT ON COLUMN companies.requires_call_unlock IS
  'TRUE when this company was created while require_call_before_access was on, so it must book its onboarding call before the portal opens. Snapshotted at creation, never re-read from the global switch. FALSE for every row that predates migration 043, which is how existing customers stay unaffected.';

COMMENT ON COLUMN companies.portal_access_granted_at IS
  'When an admin opened the portal after the onboarding call. NULL plus requires_call_unlock = TRUE means still waiting; that pair is the whole gate (needsCallUnlock in src/lib/access/call-gate.ts). Set once and kept, so a later change to the flag cannot re-lock a company that has already had its call.';

COMMENT ON COLUMN companies.portal_access_granted_by IS
  'profiles.id of the admin who opened the portal. DELIBERATELY NO FOREIGN KEY, following updated_by in migrations 034/038/039: this is an audit trail, and deleting the admin account must not either erase who granted access or block the delete.';
