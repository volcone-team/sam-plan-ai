-- 2. The vocabulary CHECKs.
--
-- ADDED SEPARATELY FROM THE COLUMNS, each preceded by DROP CONSTRAINT IF
-- EXISTS, following 036 and 040. Two reasons: re-running cannot fail on an
-- already-existing constraint, and a vocabulary that gains a value later is a
-- two-line change here rather than a column rewrite.
--
-- HOW AN ARRAY CHECK WORKS, because it is not obvious: there is no "every
-- element of this array is in that set" operator, so containment is used the
-- other way round - allowed_kinds <@ ARRAY[...] is true when every element of
-- the left side appears on the right. The explicit ::TEXT[] cast matters; an
-- untyped array literal next to a TEXT[] column is resolvable but relies on
-- inference that a later column type change would quietly break.
--
-- Each CHECK is written "IS NULL OR ..." even though <@ against NULL already
-- yields NULL (which a CHECK accepts). Stating it makes the intent legible to
-- the next reader instead of leaving them to recall Postgres three-valued
-- logic, and it is free.
-- ------------------------------------------------------------
