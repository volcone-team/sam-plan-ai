-- ============================================================
-- INITIATIVE INTAKE: LIBRARY CONFIGURATION AND INITIATIVE COLUMNS
--
-- Two things: a new admin-owned table that says how each library record
-- behaves in the picker and the form, and the columns an initiative captured
-- through that form needs.
--
-- WHY THE CONFIGURATION IS A SEPARATE TABLE AND NOT COLUMNS ON
-- wb_initiative_library. That table is REPLACED WHOLESALE on every workbook
-- upload (stated in migration 040, and ingestWorkbook does exactly that).
-- Configuration stored there would be an admin sitting down for an afternoon
-- to decide which of 87 records are offered, what kinds each may be and where
-- its revenue lands, and then losing all of it the next time the client
-- re-uploads their spreadsheet. So it lives here, joined on initiative_key
-- with NO FOREIGN KEY -- the same arrangement initiatives.library_key already
-- uses, for the same reason: a foreign key to a table that is emptied and
-- refilled would either block the upload or cascade the configuration away.
-- The cost of no FK is that a config row can outlive its library record; that
-- is a reconciliation the admin editor reports, not a constraint violation,
-- and an orphan row is harmless because every read starts from the library.
--
-- THE KEY IS initiative_key, NEVER workbook_id. The client workbook ID column
-- has 76 distinct values over 87 rows, two coexisting formats (IN001 and
-- IN11), and the collision IN010 vs IN10 which are two different initiatives.
-- It is not a key and must not be used as one. initiative_key is the
-- normalised name the whole wb_* family already joins on (migration 018).
--
-- MIRRORS LibraryRecordConfig in src/lib/intake-v3/library-config.ts, field
-- for field. That module is the single source of the vocabularies; every CHECK
-- below is one of its string unions written out in SQL. When a union changes
-- there, this is a migration, not an edit.
--
-- APPLYING THIS CHANGES NO BEHAVIOUR. The table is created empty, is_launch
-- defaults FALSE, and nothing reads the new initiatives columns yet. Same
-- stance as 043/044.
--
-- GENERATED by scripts/gen-migration-045.mjs. Edit that, not this.
-- SAFE TO RE-RUN: every statement is guarded.
-- ============================================================

-- ------------------------------------------------------------
-- 1. initiative_library_config — the per-record settings.
--
-- NO id COLUMN AND NO uuid DEFAULT: initiative_key IS the primary key, which
-- is the house convention for natural-key configuration tables
-- (app_settings 020, initiative_settings 034 both generate nothing). It also
-- makes the admin editor an upsert on the key with nothing to look up first,
-- and makes a duplicate config row for one record impossible rather than
-- merely unlikely.
--
-- ARRAYS, NOT CHILD TABLES, for the three allowed_* columns. They are read as
-- a whole, written as a whole by one admin form, never joined and never
-- aggregated; three child tables would be three joins on every picker read for
-- no query we want to make. TEXT[] with a containment CHECK, following
-- ideal_industries / cta_options / training in migration 040.
--
-- NULL AND THE EMPTY ARRAY MEAN DIFFERENT THINGS and the distinction is
-- load-bearing. NULL is "not configured yet" -- the state every row is in
-- immediately after an admin editor creates it from the library. The empty
-- array is "configured to allow nothing", which validateLibraryConfig treats
-- as a validation FAILURE for allowedKinds. Both pass the CHECK (the empty
-- array is contained in everything, and <@ against NULL yields NULL, which a
-- CHECK accepts); telling them apart is the application contract reading
-- IS NULL, which it can only do if the database keeps them distinct. So there
-- is deliberately no DEFAULT on these three.
-- ------------------------------------------------------------
CREATE TABLE IF NOT EXISTS initiative_library_config (
  initiative_key TEXT PRIMARY KEY,

  category_id TEXT,

  is_launch BOOLEAN NOT NULL DEFAULT FALSE,

  allowed_kinds TEXT[],
  allowed_paths TEXT[],
  allowed_frequencies TEXT[],

  audience_source TEXT,
  format_override TEXT,

  ongoing_label TEXT,

  partner_host BOOLEAN NOT NULL DEFAULT TRUE,
  partner_booking BOOLEAN NOT NULL DEFAULT TRUE,

  revenue_lines JSONB NOT NULL DEFAULT '[]',
  field_extras JSONB NOT NULL DEFAULT '[]',

  updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_by UUID
);

