-- ------------------------------------------------------------
-- 6. Three relaxations of the 001 initiatives table.
--
-- All three loosen; none drops, renames or rewrites anything, and none
-- touches a single row of data.
--
-- (a) activation_date NOT NULL -> nullable.
--     The new intake makes BOTH dates optional: an initiative saved with
--     neither is a valid "captured but not yet scheduled" state, which is the
--     whole point of letting someone get their plan out of their head before
--     they know when it runs. Today that save is impossible.
--     CATALOG-ONLY AND INSTANT: DROP NOT NULL clears attnotnull on the one
--     column. No table rewrite, no full scan, no rows read (dropping a
--     constraint can never need validation - only ADDING one can), so this is
--     safe on the shared production database at any time of day. It takes a
--     brief ACCESS EXCLUSIVE lock on initiatives, so it waits behind a
--     long-running read, but it holds the lock for microseconds.
--     IRREVERSIBLE IN PRACTICE, which is the one thing to weigh: putting the
--     NOT NULL back later would require every row to have a date, and by then
--     some will not.
--     Anything that assumed a non-null activation_date now needs to cope. The
--     year-at-a-glance and planner views bucket by it; an undated initiative
--     belongs in neither and must be listed separately rather than silently
--     dropped. Named as an open item.
--
-- (b) product_id NOT NULL -> nullable.
--     The spec lists Product as not required. An initiative can be captured
--     before it is decided what it sells.
--     THE FOREIGN KEY AND ITS ON DELETE RESTRICT STAY EXACTLY AS THEY ARE -
--     only the NOT NULL goes. RESTRICT is what stops a product being deleted
--     out from under a plan that references it, and a NULL product_id is not
--     a reference, so the two are orthogonal. Dropping the FK as well would
--     be a different and much worse change.
--
-- (c) kind CHECK: 'evergreen' -> 'evergreen' AND 'ongoing'.
--     001 allows one-time | recurring | evergreen. The contract
--     (InitiativeKind) says one-time | recurring | ongoing. The CHECK is
--     WIDENED to accept both rather than switched, and that is the
--     conservative order of operations: widen now, backfill later, narrow
--     only once nothing writes the old word.
--     NO BACKFILL IN THIS MIGRATION. Updating existing evergreen rows is a
--     DATA change to the one shared production database, and that is the
--     owner deliberate call made with a backup to hand - not a side effect of
--     a schema migration somebody pasted in to add a table. So until a
--     backfill happens the two words coexist in the column, and the
--     APPLICATION MUST TREAT 'evergreen' AS A LEGACY SYNONYM FOR 'ongoing' on
--     read, because task 1 contract only knows 'ongoing' and would hand an
--     evergreen row to no branch at all. Named as an open item.
--     Widening a CHECK does re-validate the column, but every existing row
--     already satisfies the old predicate and the new one is strictly weaker,
--     so the scan can only pass.
--     ONE THING TO CHECK BEFORE RUNNING SECTION 6. The 001 constraint is
--     inline and therefore auto-named, which Postgres spells
--     initiatives_kind_check. If this database spells it anything else -- a
--     trailing digit, for instance, which is what happens when the plain name
--     was already taken -- then the DROP below removes nothing, the ADD
--     succeeds, and the OLD narrow CHECK is still there refusing every
--     ongoing row while the migration reports success. Confirm first:
--       SELECT conname, pg_get_constraintdef(oid) FROM pg_constraint
