/**
 * Initiative domain types
 * The unit of planning and execution. Everything revolves around initiatives.
 */

import type { InitiativeMetricSet } from '@/lib/metrics/metric-set';

export type InitiativeKind = 'one-time' | 'recurring' | 'evergreen';
export type InitiativeStatus =
  | 'planned'
  | 'in_progress'
  | 'launched'
  | 'completed'
  | 'paused'
  | 'retired';

export interface RevenueScenarios {
  good: number; // conservative scenario
  better: number; // moderate scenario
  best: number; // aggressive scenario
}

export interface Initiative {
  id: string;
  companyId: string;
  annualPlanId: string;
  productId: string;
  initiativeTypeId: string;
  /** Workbook library key it was created from (migration 040); null for custom / older rows. */
  libraryKey?: string | null;
  /** What it tracks, frozen at creation (migration 040); null when none. */
  metricSet?: InitiativeMetricSet | null;
  // Core attributes
  name: string;
  description?: string;
  kind: InitiativeKind;
  status: InitiativeStatus;
  // Date anchors
  /** Promo launch for dated types, launch for evergreen. Null only on an unscheduled new-intake row (migration 045). */
  activationDate: Date | null;
  eventDate?: Date; // for one-time and recurring instances; null for evergreen
  /**
   * Migration 045 schedule columns. Absent or at their defaults on every row
   * the new intake did not write; read through src/lib/initiatives/schedule.ts.
   */
  revenueCloseDate?: Date | null;
  activationDatePrecision?: 'day' | 'month';
  eventDatePrecision?: 'day' | 'month';
  categoryId?: string | null;
  /** Migration 045 conversion path ('offer' | 'calls' | 'leads' | ...); null when unset. */
  conversionPath?: string | null;
  /** Migration 045 per-record answers (jsonb object). Includes lead_handoff_to / lead_goal. */
  attrs?: Record<string, unknown>;
  /**
   * How often a recurring initiative runs (migration 036 column, else
   * attrs.repeat_frequency, which the newer form writes). One of the seven
   * RepeatFrequency slugs; null for one-time / ongoing work or when unrecorded.
   */
  repeatFrequency?: string | null;
  // Planning inputs
  trafficInput?: number; // expected registrants/leads
  // Revenue projections (generated by AI or manual input)
  revenueScenarios: RevenueScenarios;
  // Budget & spending
  plannedBudget: number;
  actualSpend: number;
  spendByDate?: {
    date: Date;
    amount: number;
  }[];
  // Derived metrics
  netRevenue?: number; // good/better/best - actualSpend
  roi?: number; // (netRevenue / actualSpend) * 100
  // Display
  displayOrder: number;
  // Metadata
  createdAt: Date;
  updatedAt: Date;
}

/**
 * RecurringTemplate generates recurring initiatives
 * E.g., "2 webinars per quarter" → spawns 8 instances across the year
 */
export interface RecurringTemplate {
  id: string;
  companyId: string;
  annualPlanId: string;
  initiativeTypeId: string;
  productId: string;
  // Template configuration
  name: string;
  description?: string;
  // Schedule: e.g., "2 per quarter" means 8 instances in a year
  frequencyPerQuarter: number;
  // Lead time: promo opens N days before event
  promoOffsetDays: number;
  // Generated instances
  spawnedInstanceIds: string[];
  // Metadata
  createdAt: Date;
  updatedAt: Date;
}

